import { useCallback } from "react";
import { useRouter } from "expo-router";
import { haptic } from "./haptics";

/**
 * ====== 🆕 D-1611 — بابُ الرجوع إلى أوّل التبويب بضغطةٍ واحدة ======
 *
 * أحمد ٣١ أكتوبر بتسجيل: مراجعة ← عمل ← ملفُّ شخصيّة ← عمل ← ملفُّها… ثمّ «رجوع» مرّةً بعد مرّة حتى المجتمع — «احتاج طريقة ارجع
 * الهوب بسرعه بظغطة زر» ← «١ أ ٢ أ»: **يرجع إلى التبويب الذي بدأ منه** (الشاشاتُ المرفوعةُ كلُّها فوق مجموعة التبويبات، فإنزالُها
 * يكشف التبويبَ كما تُرك)، والبابُ **شعارُ لوبز في رأس الصفحة + الضغطُ المطوّل على زرّ الرجوع**.
 * 🔑 بابٌ واحد يناديه الاثنان: `dismissAll` كما تفعل الشاشاتُ حين تخرج إلى جذر (`TitleScreen`، `WebLayer`)، ولا شيءَ على جذرٍ
 *   لا مكدّسَ فوقه. نقرةُ الاهتزاز تقول إنّ الضغطة المطوّلة فُهمت (D-1043: الضغطُ المطوّلُ لا يكون صامتاً).
 */
export function useHomeDoor(): () => void {
  const router = useRouter();
  return useCallback(() => {
    if (!router.canDismiss()) return;
    haptic.pick();
    router.dismissAll();
  }, [router]);
}

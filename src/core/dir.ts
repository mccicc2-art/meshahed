/**
 * **اتّجاهُ نصٍّ من أوّل حرفٍ قويّ فيه** (D-241) — بيتٌ واحد لقاعدةٍ
 * يحتاجها كلُّ سطحٍ يعرض كلامَ الناس.
 *
 * **ولماذا لا `dir="auto"` دائماً:** المتصفّحُ يقرأ **أوّلَ محرفٍ قويّ في
 * العقدة**. فإن سبق النصَّ رمزٌ محايد (★) أو رقمٌ ضعيف، **قلبَ الفقرةَ
 * العربيةَ كلَّها إلى اليسار** — وهو ما وقع حرفياً في خطّ النشاط (D-228)
 * حين جاورت النجمةُ النصَّ. **فحيث يكون النصُّ وحده في عقدته `dir="auto"`
 * تكفي، وحيث يجاوره شيءٌ تُحسب الجهةُ من النصّ نفسِه.**
 *
 * **والمدى يشمل العربية والفارسية والعبرية** — لا العربيةَ وحدها:
 * **قاعدةٌ تُكتب لحرفٍ واحد تُكسَر بأوّل مستخدمٍ يكتب بغيره.**
 */
const RTL_FIRST = /^[^\p{L}]*[\p{Script=Arabic}\p{Script=Hebrew}]/u;

/** حروفُ كلِّ جهة — تُعدّ لا تُلمح */
const RTL_LETTERS = /[\p{Script=Arabic}\p{Script=Hebrew}]/gu;
const LTR_LETTERS = /[\p{Script=Latin}\p{Script=Cyrillic}\p{Script=Greek}]/gu;

/**
 * 🔴 🆕 **الجهةُ لأكثر الحروف، والتعادلُ لأوّلِ حرفٍ قويّ** (D-421،
 * بلاغُ أحمد على مؤلّف المراجعة: «إذا كتبت بالعربي في مربع الكتابة خلّ
 * الكلام يبدأ RTL»).
 *
 * **وما كان قبله: أوّلُ حرفٍ قويٍّ وحدَه.** **وهو صحيحٌ لسطرٍ واحد
 * وخاطئٌ لنصٍّ طويل**: مراجعةُ أحمد تبدأ بكلمة `Test` ثم ستُّ فقراتٍ
 * عربية — **فحرفٌ لاتينيٌّ واحدٌ كان يقلب النصَّ كلَّه إلى اليسار**،
 * **في المؤلّف وفي البطاقة معاً.**
 *
 * **والقاعدةُ الجديدة تُعمَّم ولا تُستثنى**: العدُّ يجيب في الحالة
 * الغالبة، **والأوّلُ يبقى حَكَماً عند التعادل** — فما كان يعمل يبقى
 * يعمل (اسمٌ لاتينيٌّ يبقى يساراً، وعربيٌّ يميناً)، **وما كان يفشل صار
 * يعمل.** **ودالّةٌ واحدةٌ للعرض والكتابة** — لا قاعدتان تفترقان
 * (قاعدة ٦).
 */
export function dirOf(text: string | null | undefined): "rtl" | "ltr" {
  if (!text) return "ltr";
  const rtl = (text.match(RTL_LETTERS) ?? []).length;
  if (rtl === 0) return "ltr";
  const ltr = (text.match(LTR_LETTERS) ?? []).length;
  if (ltr === 0) return "rtl";
  if (rtl === ltr) return RTL_FIRST.test(text) ? "rtl" : "ltr";
  return rtl > ltr ? "rtl" : "ltr";
}

/**
 * 🆕 **المحاذاةُ تُكتب صريحةً ولا تُترك تُستنتَج** (D-282، بلاغُ أحمد
 * مرّتين: «الكلام العربي المفروض يكون RTL» ثم «التعليق الي هو كاتبه ما
 * أشوف RTL»).
 *
 * ================= لماذا لم يكن `dir` وحدَه كافياً =================
 *
 * **كان الاعتماد على `text-align: start` يستنتج جهتَه من `direction`** —
 * وهو صحيحٌ في المواصفة. **لكنّ الفقرة المقصوصة تحمل `line-clamp` وهي
 * `display: -webkit-box`**، **وصندوقُ WebKit القديم يحلّ `start` حلّاً
 * غيرَ حلِّ الصندوق العاديّ.** فيُرسم النصُّ العربيُّ يساراً على WebKit
 * **ويُرسم يميناً على Chromium** — **وهو بعينه الفرقُ بين ما رآه أحمد
 * على iPhone وما قِستُه أنا على سطح المكتب** (`dir="rtl"` و
 * `direction: rtl` كانا حاضرين في الحالتين، والقياسُ الذي أجريتُه
 * كان صحيحاً وغيرَ كافٍ).
 *
 * **والقاعدةُ التي تبقى بعد هذا العطل بعينه:** **ما قِيس على محرّكٍ
 * واحدٍ ليس مقيساً** (أختُ D-248: satori ليس متصفّحاً)، **وخاصّيّةٌ
 * منطقيّةٌ تُحلّ داخل صندوقٍ غير قياسيّ تُكتب صريحة.**
 *
 * ⚠️ **ولا تُستعمل `text-start`/`text-end`**: هما منطقيّتان أيضاً فتقعان
 * في الحفرة نفسِها. **يمينٌ ويسارٌ صريحان هنا وحدَهما** — وهو الاستثناءُ
 * الوحيد المسموح من D-216، **لأن الجهةَ هنا محسوبةٌ من النصّ لا مفترضةٌ
 * من الواجهة.**
 */
export function alignOf(text: string | null | undefined): "text-right" | "text-left" {
  return dirOf(text) === "rtl" ? "text-right" : "text-left";
}

// عزلُ الكلمات اللاتينيّة في النصّ العربيّ — يقرؤه `legal.ts` (ملفٌّ بلا استيراد فيُختبر وحده)
/**
 * 🆕 **عزلُ الكلمات اللاتينيّة في النصّ العربيّ** (لقطةُ أحمد ٢٥ نوفمبر لصفحة الشروط): «Plus 99.99 ريالاً…» — الاسمُ اللاتينيُّ
 * والرقمُ بعده صارا كتلةً واحدةً من اليسار، فانفصل الاسمُ عن سعره عند آخر السطر وتبعثرت النقاطُ حوله. كلُّ متتاليةِ كلماتٍ لاتينيّة
 * (اسمُ منتجٍ أو متجرٍ أو خدمة، بريدٌ أو رابط، وجملةُ Trakt الإنجليزيّة) تُحاط بعلامتَي العزل غير المرئيّتين (U+2068 · U+2069)
 * فتُرسم بترتيبها داخل السطر العربيّ ولا تجرّ ما حولها، والأرقامُ تبقى خارجها فتتبع الجملةَ العربيّة.
 * 🔑 للعربيّة وحدَها، وفي العناوين والفقرات والسطر الأخير — لا في `contact` (يُرسم في سطرٍ لاتينيٍّ وحده ويُنسخ ويُضغط).
 * الويبُ (`TermsDoc`/`PrivacyDoc`) والتطبيقُ (`/api/v1/legal`) يقرآن من هنا، فيُصلَحان معاً.
 */
const LATIN_RUN = /[A-Za-z][\w.@/+:'’-]*[\w+]|[A-Za-z]/g;
const LATIN_SEQ = new RegExp(`(?:${LATIN_RUN.source})(?: (?:${LATIN_RUN.source}))*`, "g");
export function isolateLatinText(s: string): string {
  return s.replace(LATIN_SEQ, (m) => `\u2068${m}\u2069`);
}

/**
 * **مفتاحُ المنشور — بيتٌ واحد لصيغةٍ يقرؤها أربعة** (D-237).
 *
 * الصفحةُ تبني المفاتيحَ لتسأل عن أعدادها، و`ActivityFeed` تكتبها في
 * `data-post-key`، و`PostViews` تلتقطها من الشاشة، و`recordPostViews`
 * تتحقّق من بادئتها. **وصيغةٌ يقرؤها أربعةٌ ولا يملكها أحد تنكسر عند
 * أوّل تعديل** — يُغيّرها واحدٌ وينسى الثلاثة.
 *
 * **ولماذا نصٌّ لا `(نوع، رقم)`:** الصفُّ نوعان — نشرةٌ منّا وتعليقُ
 * إنسان — **ولكلٍّ هويّةٌ من شكلٍ آخر**: النشرةُ مفتاحٌ نصّيٌّ مركَّب،
 * والتعليقُ ثلاثةُ حقول. **وجدولٌ واحد يعدّهما خيرٌ من جدولين يفترقان
 * يوماً**، فالمشترَكُ الوحيدُ الذي يسعهما نصّ.
 */

/** مشاهدةُ نشرةٍ من عندنا — `n:` ثم مفتاحُ `news_posts` كما هو */
export function newsViewKey(postKey: string): string {
  return `n:${postKey}`;
}

/**
 * مشاهدةُ تعليقِ إنسان — **بصاحبه وعمله لا بمعرّفِ صفّ**.
 *
 * `reviews` مفتاحُها `(user_id, tmdb_id, media_type)` ولا `id` لها،
 * **وهي نفسُ الثلاثة التي يعرّف بها الإعجابُ والردُّ الرأيَ** — فلا
 * هويّةَ ثانية تُخترع لنفس الشيء.
 */
export function commentViewKey(
  personId: string,
  mediaType: "tv" | "movie",
  tmdbId: number,
): string {
  return `c:${personId}:${mediaType}:${tmdbId}`;
}

/**
 * **حارسُ الشكل** — يُستعمل على الخادم قبل الكتابة.
 *
 * المفاتيحُ تأتي من الـDOM، **والـDOM يعدّله من يفتح أدوات المتصفّح**:
 * بلا حارسٍ يصير الجدولُ مكاناً يكتب فيه أيُّ أحدٍ أيَّ نصّ. **والحدُّ
 * على الشكل لا على الوجود**: لا نتحقّق أن النشرةَ قائمة (نداءٌ لكل
 * مفتاح)، بل أن النصَّ يشبه مفتاحاً.
 */
export function isViewKey(k: unknown): k is string {
  return (
    typeof k === "string" &&
    k.length > 2 &&
    k.length <= 200 &&
    (k.startsWith("n:") || k.startsWith("c:"))
  );
}

/* 🆕 D-1387 — «الفحمي» مجّانيٌّ كأخيه الرسميّ (قرارُه «٢ مجاني»): الفرقُ بينهما أرضٌ وأسطح، لا زينةٌ تُشترى */
export const FREE_THEMES: readonly string[] = ["loopz", "charcoal", "amber", "daylight"] as const;


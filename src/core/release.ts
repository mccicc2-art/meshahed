/**
 * ====== 🆕 T474 — هل عُرض الفيلمُ بعد؟ ======
 *
 * أحمد ١٩ نوفمبر: «افنجرز دومزداي لقيت صفحته ف لوبز … السيء اقدر اعمل له مشاهدة !!!» — والحكمُ «١أ ٢أ ٣أ»:
 * **لا «شاهدته» ولا تقييمَ ولا رأيَ قبل تاريخ العرض الرسميّ في TMDB** (`release_date`)، **والتاريخُ الغائبُ =
 * لم يُعرض**؛ والتراجعُ عن «شاهدته» مفتوحٌ دائماً (من أخطأ قبل الحارس يصلح خطأه).
 *
 * 🔑 **«اليوم» يومُ أوّل منطقةٍ زمنيّةٍ في الدنيا** (UTC+14) لا يومُ القارئ: الفيلمُ يُفتح عند أوّل من دخل يومَ عرضه،
 * فلا يُردّ أحدٌ عن فيلمٍ يعرضه بلدُه اليوم لأنّ الخادمَ في غرينتش. والسماحُ قبل ساعاتٍ لبعض الناس أهونُ من منعِ
 * من يجلس في الصالة. **ودالّةٌ واحدةٌ للخادم والويب والتطبيق** — فلا يقول الزرُّ «مفتوح» ويرفضه الحارس.
 */

const FIRST_ZONE_MS = 14 * 3_600_000;

/** يومُ أوّل منطقةٍ زمنيّة (`YYYY-MM-DD`) */
export function releaseToday(now = Date.now()): string {
  return new Date(now + FIRST_ZONE_MS).toISOString().slice(0, 10);
}

/**
 * عُرض الفيلم؟ — تاريخُه اليومَ أو قبله. **وبلا تاريخٍ لا يُفتح إلّا ما قالت TMDB إنّه «Released»**:
 * فيلمٌ قديمٌ نسيت TMDB تاريخَه لا يُقفل على من شاهده، وإعلانٌ بلا موعدٍ يبقى مقفلاً.
 */
export function movieOut(date: string | null | undefined, status?: string | null, now = Date.now()): boolean {
  const d = typeof date === "string" ? date.slice(0, 10) : "";
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) return status === "Released";
  return d <= releaseToday(now);
}

/**
 * **تاريخٌ معروفٌ لم يأتِ بعد** — لقوائم الضغط المطوَّل: تُخفي «أشّر مشاهَداً» **حين نعرف التاريخ وحدَه**
 * (البطاقةُ لا تحمل حالةَ TMDB، والغيابُ عندها «لا أعرف» لا «لم يُعرض» — والحارسُ في الخادم يمسك الباقي).
 */
export function knownUpcoming(date: string | null | undefined, now = Date.now()): boolean {
  const d = typeof date === "string" ? date.slice(0, 10) : "";
  return /^\d{4}-\d{2}-\d{2}$/.test(d) && d > releaseToday(now);
}

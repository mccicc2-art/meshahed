/**
 * 🆕 **هل يعمل مقطعٌ الآن؟** (D-749، حكمُ أحمد: «أجّله إذا كان مقطعٌ
 * يعمل»).
 *
 * 🔑 **ولماذا وحدةٌ ثالثةٌ بينهما**: **المشغّلُ عميلٌ ثقيل، و`SwRegister`
 * سطرٌ يعمل في كلِّ صفحة** — **ولو استوردَ منه لجرَّ مشغّلَ الفيديو إلى
 * حزمة كلِّ صفحةٍ في التطبيق.** **فالوحدةُ الصغيرةُ ثمنُ ألّا يعرف
 * أحدُهما الآخر.**
 *
 * ⚠️ **ومجموعةُ رموزٍ لا عدّاد ولا راية**: **ثلاثةُ مشغّلاتٍ مركَّبةٌ
 * منذ D-745** — **ورايةٌ واحدةٌ يطفئها الخارجُ من الدور وهو غيرُ الذي
 * أشعلها**، **وعدّادٌ يختلّ عند أوّل تسريب.** **والمجموعةُ تُصحّح
 * نفسَها: من غاب حُذف رمزُه.**
 *
 * ⚠️ **ولا شيءَ هنا يخصّ الترايلرات باسمها**: **أيُّ مشغّلٍ قادمٍ
 * يستعملها** — **واسمٌ خاصٌّ بميزةٍ في وحدةٍ عامّةٍ هو كيف تُنسخ الوحدةُ
 * للميزة الثانية.**
 */
const active = new Set<object>();
const subs = new Set<() => void>();

export function setPlaybackActive(token: object, on: boolean): void {
  const had = active.size > 0;
  if (on) active.add(token);
  else active.delete(token);
  if (active.size > 0 !== had) subs.forEach((f) => f());
}

export function isPlaybackActive(): boolean {
  return active.size > 0;
}

/** **ويعود بمُلغٍ** — مستمعٌ لا يُنزع يُبقي مكوّناً ميّتاً حيّاً */
export function onPlaybackChange(f: () => void): () => void {
  subs.add(f);
  return () => {
    subs.delete(f);
  };
}

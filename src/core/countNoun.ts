/**
 * 🆕 T469 — **اسمُ المعدود في خانات الأرقام على قاعدة العدد العربيّة** (حكمُ أحمد ١٩ نوفمبر:
 * «ممكن تخليها مسلسل وفلم وتقييم في حال الأرقام زادت عن ١١»، ثم «١ أ»).
 *
 * **لماذا**: الخانةُ ثلثُ بطاقةٍ على الهاتف، و«65 مسلسلات» لا تتّسع فتُقصّ إلى «مسلسل…» —
 * والعربيّةُ نفسُها تقول بعد الأحد عشر «مسلسلاً» مفرداً، فالمفردُ هو الأصحُّ والأقصرُ معاً.
 *
 * - **من ٣ إلى ١٠، والصفر**: الجمعُ كما هو («مسلسلات · أفلام · تقييماتي»).
 * - **١ و٢**: المفرد — بعد رقمٍ مكتوبٍ يُقرأ «2 مسلسل» طبيعيّاً، و«مسلسلان» بعد الرقم تكرارٌ للعدد.
 * - **من ١١ إلى ٩٩**: المفردُ منوَّناً («65 مسلسلًا») — 🆕 T502 (انظر `AR_TAN`).
 * - **١٠٠ فأكثر**: المفرد **دائماً** بلا تنوين — ⚖️ لا القاعدةُ الكاملةُ بآخر رقمين (حكمُه «١ أ»):
 *   تلك تعيد «103 مسلسلات» فتُقصّ الخانةُ من جديد، وهي المشكلةُ التي جاء الطلبُ لأجلها.
 *
 * **والإنجليزيّةُ لا تتغيّر**: تُعاد الكلمةُ التي جاءت من القاموس كما هي.
 * **والمفرداتُ هنا لا في القاموس**: هي جزءٌ من القاعدة نفسِها (صيغةُ المعدود)، لا اسمٌ لسطحٍ يُترجَم.
 */
export type CountNoun = "shows" | "movies" | "ratings" | "followers";

const AR_ONE: Readonly<Record<CountNoun, string>> = {
  shows: "مسلسل",
  /* «فيلم» لا «فلم»: الكتابةُ التي في كلِّ موضعٍ آخر من التطبيق (`typeMovie` · `shareMovies`) */
  movies: "فيلم",
  ratings: "تقييم",
  followers: "متابِع",
};

/**
 * 🆕 T502 — **التمييزُ منصوبٌ منوَّنٌ من ١١ إلى ٩٩** (أحمد ٢٢ نوفمبر، «٧ د» بعد أن رأى الصيغ: «وين متابعًا؟»): «20 متابِعًا»
 * و«65 مسلسلًا» كما تقولها الفصحى — في الملفّ وخانات الإحصاءات معاً، فلا يكون للقاعدة الواحدة أسلوبان.
 * ومن المئة فما فوق يبقى المفردُ بلا تنوين («150 مسلسل») — حكمُ «١ أ» في ١٩ نوفمبر، وهو في الفصحى مضافٌ («مئةُ مسلسلٍ») لا تمييز.
 */
const AR_TAN: Readonly<Record<CountNoun, string>> = {
  shows: "مسلسلًا",
  movies: "فيلمًا",
  ratings: "تقييمًا",
  followers: "متابِعًا",
};

/** 🆕 T502 — جمعٌ لا يحمله القاموس: كلمةُ القاموس للمتابِعين مفردةٌ («متابِع») لأنها كانت تُكتب بعد أيِّ عدد */
const AR_MANY: Readonly<Partial<Record<CountNoun, string>>> = { followers: "متابِعين" };

/** `many` اسمُ الخانة من القاموس (الجمع) — يُعاد كما هو حيث لا تنطبق القاعدة */
export function countNoun(locale: string, noun: CountNoun, n: number, many: string): string {
  if (locale !== "ar") {
    /* الإنجليزيّةُ لا تتغيّر — إلّا «follower» للواحد: كلمةُ القاموس «followers» صارت تُكتب بعد العدد (T502) */
    return noun === "followers" && n === 1 ? "follower" : many;
  }
  if (n >= 11 && n <= 99) return AR_TAN[noun];
  if (n === 1 || n === 2 || n >= 100) return AR_ONE[noun];
  return AR_MANY[noun] ?? many;
}

/**
 * 🆕 T469 — **اسمُ المعدود في خانات الأرقام على قاعدة العدد العربيّة** (حكمُ أحمد ١٩ نوفمبر:
 * «ممكن تخليها مسلسل وفلم وتقييم في حال الأرقام زادت عن ١١»، ثم «١ أ»).
 *
 * **لماذا**: الخانةُ ثلثُ بطاقةٍ على الهاتف، و«65 مسلسلات» لا تتّسع فتُقصّ إلى «مسلسل…» —
 * والعربيّةُ نفسُها تقول بعد الأحد عشر «مسلسلاً» مفرداً، فالمفردُ هو الأصحُّ والأقصرُ معاً.
 *
 * - **من ٣ إلى ١٠، والصفر**: الجمعُ كما هو («مسلسلات · أفلام · تقييماتي»).
 * - **١ و٢**: المفرد — بعد رقمٍ مكتوبٍ يُقرأ «2 مسلسل» طبيعيّاً، و«مسلسلان» بعد الرقم تكرارٌ للعدد.
 * - **١١ فأكثر**: المفرد **دائماً** — ⚖️ لا القاعدةُ الكاملةُ بآخر رقمين (حكمُه «١ أ»):
 *   تلك تعيد «103 مسلسلات» فتُقصّ الخانةُ من جديد، وهي المشكلةُ التي جاء الطلبُ لأجلها.
 *
 * **والإنجليزيّةُ لا تتغيّر**: تُعاد الكلمةُ التي جاءت من القاموس كما هي.
 * **والمفرداتُ هنا لا في القاموس**: هي جزءٌ من القاعدة نفسِها (صيغةُ المعدود)، لا اسمٌ لسطحٍ يُترجَم.
 */
export type CountNoun = "shows" | "movies" | "ratings";

const AR_ONE: Readonly<Record<CountNoun, string>> = {
  shows: "مسلسل",
  /* «فيلم» لا «فلم»: الكتابةُ التي في كلِّ موضعٍ آخر من التطبيق (`typeMovie` · `shareMovies`) */
  movies: "فيلم",
  ratings: "تقييم",
};

/** `many` اسمُ الخانة من القاموس (الجمع) — يُعاد كما هو حيث لا تنطبق القاعدة */
export function countNoun(locale: string, noun: CountNoun, n: number, many: string): string {
  if (locale !== "ar") return many;
  return n === 1 || n === 2 || n >= 11 ? AR_ONE[noun] : many;
}

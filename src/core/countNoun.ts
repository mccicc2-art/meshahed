/**
 * **اسمُ المعدود في خانات الأرقام** — بطاقةُ الرئيسيّة وبطاقةُ الملفّ وسطرُ المتابِعين.
 *
 * التاريخ: T469 (١٩ نوفمبر) جعله على قاعدة العدد العربيّة لأنّ «65 مسلسلات» تُقصّ في خانةٍ هي ثلثُ بطاقة، ثمّ T502 نوّنه من ١١
 * إلى ٩٩ («65 مسلسلًا»). 🆕 T529 — صار كلمةً ثابتة (انظر `AR_FIXED`).
 *
 * **والمفرداتُ هنا لا في القاموس**: هي صيغةُ المعدود بعد الرقم، لا اسمٌ لسطحٍ يُترجَم.
 */
export type CountNoun = "shows" | "movies" | "ratings" | "followers";

/**
 * 🆕 T529 — **كلمةٌ ثابتةٌ بعد أيِّ عدد** (أحمد ٢٣ نوفمبر بلقطتين: «تكون مسلسل فيلم تقييم» و«استخدم صيغ تويتر العربية»،
 * ثمّ «المتابعون خلها المتابعون» و«وين الكسرة»): نقضٌ لقاعدة العدد في T469/T502 («65 مسلسلًا» · «20 متابِعًا») بيد صاحبها.
 * الخانةُ عنوانٌ تحت رقم لا جملة، والكلمةُ التي تتبدّل مع كلِّ عددٍ تُقرأ تذبذباً — فالمفردُ للأعمال والتقييمات، و«المتابِعون»
 * بالكسرة (تُفرّقها عن «المتابَعون») كما تكتبها منصّةُ X. الإنجليزيّةُ كما كانت.
 */
const AR_FIXED: Readonly<Record<CountNoun, string>> = {
  shows: "مسلسل",
  /* «فيلم» لا «فلم»: الكتابةُ التي في كلِّ موضعٍ آخر من التطبيق (`typeMovie` · `shareMovies`) */
  movies: "فيلم",
  ratings: "تقييم",
  followers: "المتابِعون",
};

/** `many` اسمُ الخانة من القاموس — يُعاد كما هو في الإنجليزيّة */
export function countNoun(locale: string, noun: CountNoun, n: number, many: string): string {
  if (locale !== "ar") {
    /* الإنجليزيّةُ لا تتغيّر — إلّا «follower» للواحد: كلمةُ القاموس «followers» صارت تُكتب بعد العدد (T502) */
    return noun === "followers" && n === 1 ? "follower" : many;
  }
  return AR_FIXED[noun];
}

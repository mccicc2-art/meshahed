/**
 * ====== ترتيبُ مراجعات العمل — قاعدةٌ واحدةٌ للويب والتطبيق (D-1567) ======
 *
 * أحمد ٢٩ أكتوبر (على لقطة تبويب المراجعات): «مراجعات لوبز تنزل تحت والترتيب يكون للأكثر إعجاب، وطبعاً صاحب المراجعة يشوف
 * مراجعته أول شي» — ثمّ «٢أ»: عند التساوي الأحدثُ أوّلاً.
 *
 * 🔑 **ثلاثُ طبقاتٍ ثمّ الإعجاب**: مراجعةُ صاحب الحساب أوّلاً (يرى ما كتب حيث يتوقّعه) · ثمّ مراجعاتُ الأعضاء · ثمّ مراجعاتُ
 *   شخصيّات لوبز AI تحتها كلِّها — فرأيُ الناس يتصدّر ولا تُغرقه خمسُ شخصيّاتٍ تكتب كلَّ ساعة. **وداخلَ كلِّ طبقةٍ الأكثرُ
 *   إعجاباً**، والتساوي للأحدث. والطوابعُ ISO من الخادم نفسِه فترتيبُ حروفها ترتيبُ زمنها.
 * ⚠️ **في مكانٍ واحد** لأنّ مسارَ التطبيق (`/api/v1/title/…/community`) وتبويبَ الويب (`TitleCommunityTab`) يرتّبان القائمةَ
 *   نفسَها — ترتيبان لتبويبٍ واحد يربك من يفتحه هنا وهناك.
 */
export interface RankedReview {
  mine: boolean;
  /** مراجعةُ شخصيّةٍ من شخصيّات لوبز AI */
  ai: boolean;
  likes: number;
  /** ISO */
  at: string;
}

const tier = (r: RankedReview) => (r.mine ? 0 : r.ai ? 2 : 1);

export function compareReviews(a: RankedReview, b: RankedReview): number {
  return tier(a) - tier(b) || b.likes - a.likes || (a.at < b.at ? 1 : a.at > b.at ? -1 : 0);
}

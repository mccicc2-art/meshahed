import { handle } from "@/lib/v1";
import { ok } from "@/core/contracts/result";

/**
 * ====== `GET /api/v1/app/flags` — مفاتيحُ التطبيق من الخادم (D-1140 · Phase 11-K · K2) ======
 *
 * **لماذا**: K2 تنقل سحبَ التبويبات من خيط JS إلى خيط الواجهة — أكبرُ تغييرٍ في إحساس
 * التطبيق منذ D-970. **تنزل عبر الهواء مطفأةً**، وتُشغَّل من هنا بلا تحديثٍ ثانٍ للتطبيق،
 * وتُطفأ من هنا في دقائق إن ساءت. والعلاماتُ توسم `k2=0/1` فيُقارن الجهازُ بنفسه.
 *
 * 🔑 **ثابتٌ في الكود لا جدولٌ ولا متغيّرُ بيئة**: جدولٌ = هجرةٌ بيد أحمد، ومتغيّرُ البيئة
 * لا يُقرأ بلا نشرٍ أصلاً (`[deploy]` — D-840). فالتبديلُ **رقعةُ ويبٍ بسطرٍ واحد**: بناءُ
 * Vercel واحد، ولا بناءَ EAS ولا تحديثَ للتطبيق.
 *
 * ⚖️ **عامٌّ بلا هويّة**: لا رمزَ مطلوباً — التطبيقُ يسأل قبل أن يملك رمزاً، والردُّ واحدٌ
 * للجميع فيُخزَّن دقيقةً. **ويُطبَّق عند الفتح التالي للشاشة** (`TabSlide` يختار مسارَه مرّةً
 * عند التركيب — لا تبديلَ آليّةٍ والإصبعُ على الشاشة).
 */
const FLAGS = {
  /* D-1140 — K2 (السحبُ على خيط الواجهة). 🆕 D-1145 — **مشغَّل** (أحمد: «نفذ 1 و 2»، ٢٦ سبتمبر).
     الإطفاءُ عند أيِّ عيب: `false` هنا ثمّ رقعةُ ويب `[deploy]` — يعود المسارُ القديمُ عند الفتح التالي للشاشة */
  k2: true,
  /* 🆕 D-1262 — `tx`: صفحةُ العمل لا تنتظر الإعلان؛ التطبيقُ يطلبه وحدَه من `…/trailer`. **تجربة**:
     الإلغاءُ = `false` هنا ثمّ رقعةُ ويب `[deploy]` — يعود الردُّ الواحدُ كما كان خلال دقائق، بلا تحديثٍ للتطبيق */
  tx: true,
} as const;

/**
 * 🆕 K4b — **التطبيقُ يملك جلستَه** (`/api/v1/session/mint`): مطفأٌ للجميع، ويُشغَّل **لأجهزةٍ بأسمائها
 * أوّلاً** (طرازُ الهاتف كما تحمله علاماتُ الأداء، `?m=`) قبل أن يصير عامّاً. الطرازُ ليس هويّةً ولا
 * سرّاً — هو مجرّدُ حصرٍ للتجربة. أيُّ عيبٍ ⇒ يُفرَّغ السطرُ برقعة ويب ويعود الجسرُ كما هو.
 */
/* 🆕 K4b — للجميع (أحمد، ٢٧ سبتمبر: «ارفع الكل») بعد نجاح جوال خالد: سكٌّ من الكوكي، تجديدٌ ذاتيٌّ بعد ساعة، خروجٌ ودخولٌ سليمان، ولا تصادمَ في `auth.sessions` */
const K4_ALL = true;
/* 🆕 K4b — جوالُ خالد أوّلاً (أحمد: «جهاز خالد»، ٢٧ سبتمبر) */
const K4_MODELS: readonly string[] = ["SM-S928B"];

export async function GET(req: Request) {
  const m = new URL(req.url).searchParams.get("m") ?? "";
  const k4 = K4_ALL || K4_MODELS.includes(m);
  return handle(async () => ok({ ...FLAGS, k4 }, []), { cacheControl: "public, max-age=60, s-maxage=60" });
}

import { NextResponse } from "next/server";
import { createServiceClient } from "@/lib/supabase/service";
import { allow } from "@/lib/ratelimit";

/**
 * 🆕 **عدّادُ لغاتِ الزوّار** (D-666، طلبُ أحمد: «فعّل العدّاد») —
 * **بابُ قياسٍ لا ميزة.**
 *
 * ================= لماذا نداءٌ لا وسيط =================
 *
 * **الوسيطُ يجري على كلِّ طلبٍ في العالم** — نداءُ قاعدةٍ فيه يدفع ثمنَه
 * **كلُّ صفحةٍ في زمن أوّلِ بايت** (D-508/D-510: **لا يدفع مستخدمٌ كلفةَ
 * ما لا يراه**). **وهذا النداءُ يُطلق مرّةً في الجلسة، بعد الرسم،
 * `keepalive`** — **فلا يقف بينه وبين الصفحة شيء.**
 *
 * ================= ولا يُرسل العميلُ شيئاً =================
 *
 * **اللغةُ تُقرأ من ترويسة `accept-language` هنا** — **فلا يُصدَّق نصٌّ
 * يرسله متصفّح**، والعميلُ ينادي بابَه فارغاً. **وأوّلُ وسمٍ وحدَه**
 * (أعلى `q`) — **قائمةُ تفضيلاتٍ كاملةٍ تصير بصمةً تعرّف صاحبَها**،
 * **وسمٌ واحدٌ لا.**
 *
 * ================= وما لا يُخزَّن لا يُسرَّب =================
 *
 * **الصفُّ يومٌ ولغةٌ وعدد** — لا IP ولا معرّفَ مستخدمٍ ولا مسار.
 * **وعنوانُ الطلب يُقرأ في الذاكرة لحاجزِ المعدّل ولا يُكتب** (وصفةُ
 * `lib/ratelimit` القائمة).
 *
 * ⚠️ **والفشلُ صامتٌ دائماً** (204 في كلِّ حال): **عدّادُ فضولٍ يكسر
 * صفحةً هو أسوأُ صفقةٍ ممكنة** — **والرقمُ الناقصُ خيرٌ من صفحةٍ
 * ناقصة.**
 */
export async function POST(req: Request) {
  try {
    const ip =
      req.headers.get("x-forwarded-for")?.split(",")[0]?.trim() || "unknown";
    /* عشرُ نبضاتٍ لكلِّ عنوانٍ في عشر دقائق — الجلسةُ الواحدة تنبض مرّةً،
       وما زاد حلقةٌ لا زائر. **والحاجزُ لكلِّ نسخةِ دالّةٍ على حدة**
       (نصُّ `lib/ratelimit`)، وهو يكفي هنا: الرقمُ اتّجاهٌ لا محاسبة. */
    if (!allow(`lang:${ip}`, 10, 600_000)) {
      return new NextResponse(null, { status: 204 });
    }

    const first =
      (req.headers.get("accept-language") ?? "").split(",")[0]?.split(";")[0]?.trim() ?? "";
    if (!first) return new NextResponse(null, { status: 204 });

    // عميلُ الخدمة (D-898): بابُ العدّاد هذا المسارُ وحاجزُه، لا PostgREST مباشرةً
    const supabase = await createServiceClient();
    await supabase.rpc("bump_visit_lang", { p_lang: first });
  } catch {
    /* لا شيء — انظر رأسَ الملفّ */
  }
  return new NextResponse(null, { status: 204 });
}

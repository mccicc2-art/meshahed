import { getUserId } from "@/lib/data";
import { NativeLibraryFlag } from "./NativeLibraryFlag";

/**
 * **بوّابةُ الشاشات الأصليّة** (Phase 11 · B1، D-936 §٢.٢ → **D-1002**).
 *
 * كانت محسومةً بـ`profiles.is_admin` (المالكُ وKHLD — D-923) حتى تنضج التجربة.
 * 🔴 **D-1002 (١٧ سبتمبر ٢٠٢٦ — قرارُ أحمد: «دائماً خلّ الشاشات الأصليّة عند الكلّ»)**:
 * المختبرون وصلهم 1.9.1 ورأوا «اكتشف» والمكتبةَ ويبيّتين. **الشرطُ الآن: مستخدمٌ
 * مسجَّل داخل الغلاف** — لا إدارة. الزائرُ يبقى ويبيّاً (المكتبةُ تحتاج تسجيلاً
 * أصلاً، D-856). **قرارٌ دائم**: لا يُعاد الحبسُ خلف الإدارة في تجربةٍ قادمة؛ ما
 * يحتاج تجربةً مغلقة يُحكم بعلَمٍ خاصٍّ به لا بهذه البوّابة.
 *
 * ⚖️ **ولا يحبس أوّلَ بايت** (D-122): `getUserId` رحلةُ جلسة، **فالمكوّنُ يُغلَّف
 * بـ`Suspense` في التخطيط** — يصل حين يجهز. **ولا يُركَّب إلا داخل الغلاف** (وسم
 * `LoopzApp/` على الخادم).
 */
export async function NativeLibraryGate() {
  const uid = await getUserId().catch(() => null);
  if (!uid) return null;
  return <NativeLibraryFlag />;
}

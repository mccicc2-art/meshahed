"use client";

import Image from "next/image";
import { useState } from "react";

/**
 * 🆕 **غلافٌ يسقط نداؤه يعود إلى التدرّج، لا إلى أيقونةِ صورةٍ مكسورة**
 * (D-657، ما رأيتُه في ملفّ khld: مربّعٌ صغيرٌ بعلامة استفهام أعلى
 * الغلاف).
 *
 * 🔴 **ورابطُ الغلاف محفوظٌ في الصفّ والملفُّ قد يزول من المخزن**:
 * صورةٌ حُذفت أو رفعٌ لم يكتمل **يتركان رابطاً يشير إلى لا شيء** —
 * **والمتصفّحُ يرسم أيقونةَ الكسر، وهي تُقرأ عطلاً في التطبيق لا نقصاً
 * في صورة** (D-181: ما لا يوجد يُقال، ولا يُرسم مكسوراً).
 *
 * 🔑 **والتدرّجُ هو الحالةُ الصادقة**: هو ما يراه من لا غلافَ له أصلاً
 * — **فمن سقط غلافُه يرى ما يراه من لا غلافَ له**، ولا شكلَ ثالثٌ
 * يُخترع لحالةٍ ثالثة (القاعدة ٣).
 *
 * ⚠️ **والتدرّجُ يُرسم دائماً تحته لا في فرعٍ مقابل**: **صورةٌ تفشل بعد
 * الرسم لا تعيد تشغيل الفرع** — فيجب أن يكون تحتها أصلاً.
 */
export function CoverImage({
  src,
  posY,
}: {
  src: string;
  /** موضعُ القصّ الذي اختاره صاحبُه (D-131) */
  posY: number | null;
}) {
  const [failed, setFailed] = useState(false);
  if (failed) return null;
  return (
    <Image
      src={src}
      alt=""
      fill
      priority
      sizes="(max-width: 640px) 100vw, 1152px"
      className="object-cover"
      style={{ objectPosition: `50% ${posY ?? 30}%` }}
      onError={() => setFailed(true)}
    />
  );
}

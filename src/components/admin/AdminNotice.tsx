import { ADMIN_OK, adminErrorAr } from "@/lib/admin";

/**
 * 🆕 **إشعارُ الإدارة الواحد** (D-963، البند (ز) من مراجعة ١٤ سبتمبر).
 *
 * 🔴 **ما كان**: ستُّ صفحاتِ إدارةٍ تكتب البانرَ نفسَه بيدها —
 * `{sp.err && <p className="text-14 text-[color:var(--error)]">⚠ …</p>}`
 * **مكرَّراً حرفاً**، **ونصفُها يطبع رسالةَ PostgREST خاماً بالإنجليزيّة**
 * والنصفُ الآخر يملك خريطتَه العربيّةَ الخاصّة. **شكلان لشيءٍ واحدٍ عيبٌ لا
 * خيار** (القاعدة ٦)، **وخريطتان لشيءٍ واحدٍ مثلُه** (القاعدة ٣).
 *
 * 🔑 **والترجمةُ في `src/lib/admin.ts` لا هنا**: المكوّنُ يرسم، والخريطةُ
 * تُقرأ من مكانٍ واحدٍ يجاور `AUDIT_AR` — **فمن يضيف فعلاً إداريّاً يجد
 * جدوليه متجاورين.**
 *
 * 🔑 **و`role="status"` لأنّ الرسالةَ تصل بعد تحويلٍ لا بضغطةٍ في مكانها**
 * (القاعدة ١٦): قارئُ الشاشة يصل الصفحةَ من رأسها **فلا يمرّ بالبانر إلا
 * بعد سطرين** — والإعلانُ الحيُّ يقوله فورَ الرسم. **والخطأ `assertive`
 * والنجاح `polite`**: أحدهما يقطع، والآخر ينتظر دورَه.
 *
 * ⚖️ **ولا يُرسم شيءٌ حين لا خبرَ**: `null` لا صندوقٌ فارغٌ يحجز سطراً في
 * كلِّ فتحة.
 */
export function AdminNotice({
  err,
  ok,
  okText,
}: {
  err?: string;
  ok?: string;
  /** نصُّ نجاحٍ يخصّ الصفحة — حين لا يكفي جدولُ `ADMIN_OK` العامّ (الروابط). */
  okText?: string;
}) {
  const e = adminErrorAr(err);
  const o = ok ? (okText ?? ADMIN_OK[ok] ?? "تمّ") : null;
  if (!e && !o) return null;

  return (
    <div className="space-y-1">
      {e && (
        <p role="alert" className="text-14 text-[color:var(--error)]">
          ⚠ {e}
        </p>
      )}
      {o && (
        <p role="status" className="text-14 text-[color:var(--success)]">
          ✓ {o}
        </p>
      )}
    </div>
  );
}

import Link from "next/link";
import Image from "next/image";
import type { Locale } from "@/lib/i18n";
import { BackButton } from "./BackButton";
import { Icon } from "./Icon";

/**
 * **ترويسةُ العمل — غلافٌ واحد لكل صفحات الكلام** (D-244، طلبُ أحمد على
 * صفحة التعليق: «أحتاج الغلاف تبع الفلم فوق»).
 *
 * ================= لماذا خرجت من صفحة `/talk` =================
 *
 * وُلدت داخلها (D-216/D-217) وكانت وحيدةَ القارئ. **ثم طلبها أحمد فوق
 * صفحة التعليق** — وقارئٌ ثانٍ هو لحظةُ الاستخراج عندنا (نفسُ سيرة
 * `Composer` و`Dropdown` و`newsLine`): **تُنسخ فتفترق النسختان في الحشو
 * والتدرّج بعد أسبوع، وتُستخرج فتبقى غلافاً واحداً في السطحين.**
 * والنسخةُ المحلّية حُذفت في الدفعة نفسِها.
 *
 * ================= الهندسة (كما ضُبطت في D-217) =================
 *
 * `25svh` بحدَّين (`min-h`/`max-h`) — **والنسبةُ وحدها بلا حدّين تكسر
 * أحدَ الطرفين دائماً**. و`-mt-6 -mx-4` تُلغي حشوَ التخطيط بالضبط لا
 * بالتقدير. والزرّان زجاجيّان بقطر لمسٍ ٤٤، **في `start`/`end` لا
 * يسار/يمين** فينقلبان وحدَهما في العربية.
 *
 * **وطرفُ النهاية وسيطٌ (`end`) لا زرٌّ مبنيّ هنا**: صفحةُ الغرفة تضع
 * سهماً إلى صفحة العمل، وصفحةُ التعليق تضع باباً إلى الغرفة — **الموضعُ
 * ثابتٌ والفعلُ لصاحب الصفحة.**
 */
/* ⚖️ **وقُصَّ النصفُ** (D-284، طلبُ أحمد: «مساحة المسلسل كبيرة جدًّا
   وبدون فايدة، قلّلها للنص»): كان `25svh` بحدٍّ أدنى ١٩٠px وأقصى ٣٠٠.
   **وكان الفراغُ يشتري صورةً لا تُقرأ**: الغلافُ خافتٌ تحت تدرّجين،
   **والقارئُ جاء للكلام لا للصورة** — فسرقت الترويسةُ ثلثَ الشاشة الأولى
   من الحوار الذي هو سببُ الصفحة.
   **والمقاسُ الجديد يسع ما يجب أن يُقرأ ولا يزيد**: الملصقُ ٨٧px والحشوُ
   ١٢، فالحدُّ الأدنى ١٢٨ يكفيهما بلا قصّ (D-046: لا شيء يتغيّر حجمه بعد
   أن يُرسم). **وهي مشتركةٌ مع `/review`** — سطحان أخوان بمقاسٍ واحد
   (D-244). */
export function TitleHero({
  backdrop,
  poster,
  title,
  href,
  mediaType,
  avg,
  count,
  ratingLabel,
  locale,
  end,
  meta,
}: {
  /** روابطُ صورٍ كاملة — المستدعي يملك قرارَ «فنّي أم رسميّ» (D-131) */
  backdrop: string | null;
  poster: string | null;
  title: string;
  /** الملصقُ والاسمُ رابطٌ واحد إلى هذا المسار */
  href: string;
  mediaType: "tv" | "movie";
  /** متوسّطُ الجماعة — **ومقامُه معه** (D-216): «٩٫٥» من اثنين ليست من ألف */
  avg?: number;
  count?: number;
  ratingLabel?: string;
  locale: Locale;
  /** الزرُّ العائم في طرف النهاية — انظر أعلاه */
  end?: React.ReactNode;
  /**
   * 🆕 **سطرُ الحقائق تحت الاسم** (D-286، طلبُ أحمد: «اسم المسلسل ارفعه
   * فوق وحط تحته تقييمه من IMDb والتصنيف العمري»).
   *
   * **وهو وسيطٌ لا محتوًى يُبنى هنا** — لسببِ `end` نفسِه: التقييمُ رحلةٌ
   * إلى OMDb، **وترويسةٌ تنتظر شبكةً قبل أن تُرسم عطلٌ لا ميزة.**
   * فيمرّره المستدعي داخل `Suspense` بهيكلٍ بارتفاع السطر (D-046).
   */
  meta?: React.ReactNode;
  /**
   * 🆕 **سطرٌ خافتٌ أسفلَ الكتلة** (D-286، طلبُ أحمد: «اكتب العنوان في
   * المساحة في الغلاف»). **كان في الغلاف فراغٌ وتحته صفحةٌ مزدحمة** —
   * فصعد وصفُ الغرفة إلى الفراغ، **وبدأ متنُ الصفحة بما جاء له القارئ.**
   */
}) {
  return (
    /* ⚖️ **وعادت ١٦px من الستّة والستّين التي قُصّت** (D-286): D-284 قصّت
       الترويسةَ إلى ١٢٨px، **وكان ذلك صواباً لِما كانت تحمله يومَها** —
       اسمٌ وحدَه. **ثم صارت تحمل ثلاثةَ أسطرٍ وملصقاً وزرَّين، والمقاسُ
       يتبع ما يوضع فيه** (D-229). **والحسابُ صريحٌ لا ذوق:** صفُّ الزرَّين
       ٥٦px من الأعلى، والملصقُ ٧٥ مع حشوٍ ١٢ من الأسفل — **فأقلُّ ارتفاعٍ
       لا يتلامسان عنده ١٤٤.** **وعند ١٢٨ كان زرُّ الرجوع يقف على الملصق
       فعلاً** — يُرى في لقطة أحمد، **ولم يمسكه أيُّ فحصٍ لأنّ التلامسَ
       ليس خطأً.**
       🆕 **والحسابُ أُعيد في D-288 والارتفاعُ لم يتغيّر:** السهمُ العاري
       يشغل ٨+٢٤ = **٣٢ من الأعلى** (وهدفُ لمسه ينتهي عند ٤٢)، والملصقُ
       عاد ٨٧+١٢ = **٩٩ من الأسفل** فرأسُه عند ٤٥. **فبقيت الفرجةُ ٣px
       بعد أن كبر الملصقُ وصغُر السهم** — **وهو ما يجعل الطلبين متوافقين
       لا متعارضين.** */
    <header className="relative -mt-6 -mx-4 h-[16svh] min-h-[144px] max-h-[180px] overflow-hidden bg-surface-2">
      {backdrop && (
        <Image src={backdrop} alt="" fill sizes="100vw" priority className="object-cover" />
      )}
      {/* تدرّجان: واحدٌ يُلبس الصورةَ سواداً كي يُقرأ الاسمُ فوقها مهما
          كان لونها، وآخرُ من الأعلى كي يُقرأ الزرّان */}
      <div className="absolute inset-0 bg-gradient-to-t from-background via-background/70 to-transparent" />
      <div className="absolute inset-x-0 top-0 h-24 bg-gradient-to-b from-black/50 to-transparent" />

      {/* 🆕 **الصفُّ يُحاذى من الأعلى لا من الوسط** (D-288): السهمُ صار
          ٢٤px والزرُّ المقابل ٤٤، **و`items-center` كانت تُنزل السهمَ إلى
          منتصف الأطول فتُلغي رفعَه.** **والحشوُ ١٢ → ٨** — وهو ما طلبه
          أحمد بـ«ارفعه فوق». */}
      {/* 🔴 🆕 **والاسمُ صعد إلى الشريط العلويّ** (D-304، طلبُ أحمد
          بلقطةٍ عليها دائرةٌ حمراء في الفراغ الأعلى: «العنوان يكون في
          المكان الأحمر»).
          **وكان يزاحم الملصقَ على عمودٍ ارتفاعُه ٨٧px** — ومعه تقييمُنا
          وIMDb والتصنيفُ والوصف: **خمسةُ سطورٍ في مكانِ أربعة**، وهو ما
          أنتج ميلَ D-297 وعلاجَه الجزئيَّ في D-303.
          **والفراغُ الحقيقيُّ كان فوق، بجانب السهم** — **فذهب الاسمُ
          إليه، وسقط الميلُ من أصله لا بتضييق السطور** (D-266: أرخصُ
          مساحةٍ هي القائمة). */}
      <div className="absolute inset-x-0 top-0 px-3 pt-2 flex items-start gap-3">
        <BackButton locale={locale} variant="bare" />
        {/* ⚠️ **وسطرٌ واحدٌ يُقصّ**: الشريطُ عرضُ الشاشة كلِّها الآن
            **فالاسمُ الطويلُ نادرٌ أن يُقصّ**، **وصفحتُه على بُعد ضغطةٍ
            من الملصق** (D-297). */}
        <h1 className="min-w-0 flex-1 mt-px font-bold text-[22px] leading-tight line-clamp-1 text-white drop-shadow">
          {title}
        </h1>
        {end}
      </div>

      <div className="absolute inset-x-0 bottom-0 px-4 sm:px-6 pb-3 flex items-end gap-3">
        {/* الملصقُ والاسمُ رابطٌ واحد — هدفُ لمسٍ واسع، ولا زرَّ داخل زرّ */}
        <Link
          href={href}
          className="flex items-end gap-3 min-w-0 flex-1 active:opacity-80 transition"
        >
          {/* ⚖️ **والملصقُ عاد ٥٨×٨٧** (D-288، نصُّ أحمد: «إيه صغّرت حجم
              البوستر!! أنا ما طلبت منك — رجّعه نفس حجمه»).
              **وتصغيرُه في D-286 كان قراراً لم يُطلَب**: احتجتُ ١٢px
              لأسطرٍ جديدة **فأخذتُها من عنصرٍ لم يشتكِ منه أحد** بدل أن
              أقولها وأسأل. **والثمنُ يُدفع من الارتفاع لا من عنصرٍ في
              الشاشة** — والارتفاعُ باقٍ ١٤٤ لأن السهمَ العاري صار يقف
              في ٣٢px بدل ٥٦ (انظر أعلاه). */}
          <div className="relative w-[58px] h-[87px] shrink-0 rounded-xl overflow-hidden bg-surface-2 border border-white/15 shadow-xl">
            {poster ? (
              <Image src={poster} alt="" fill sizes="58px" className="object-cover" />
            ) : (
              <span className="absolute inset-0 grid place-items-center text-muted">
                <Icon name={mediaType === "tv" ? "tv" : "film"} size={18} />
              </span>
            )}
          </div>
          {/* 🆕 **والعمودُ بارتفاع الملصق، فرأسُ الاسم عند رأسه** (D-297،
              طلبُ أحمد: «اسم المسلسل خلّه موازي لبداية الصورة، ارفعه
              فوق»).
              **وكان العمودُ يُحاذى من القاع وحدَه** — فارتفاعُه ارتفاعُ
              محتواه، **واسمُه يبدأ حيث انتهى الحساب لا حيث يبدأ الملصق**:
              كتلتان متجاورتان يتّفق قاعُهما ويختلف رأسُهما **تُقرآن
              مائلتين** (D-046: ما يُرسم متجاوراً يُحاذى قصداً).
              **و`min-h` لا `h`**: اسمٌ يطول أو تقييمٌ يحضر **يمدُّ العمودَ
              صعوداً ولا يفيض تحته**، **فالقاعُ يبقى مِرساةً** (D-224). */}
          <div className="min-w-0 flex-1 min-h-[87px] flex flex-col">
            {/* ⚠️ **سطرٌ واحدٌ لا سطران** (D-286): تحت الاسم صار سطران،
                **واسمٌ يأخذ سطرين يدفعهما إلى صفِّ الزرّين.** والاسمُ
                الطويلُ يُقصّ هنا **وصفحتُه على بُعد ضغطة.** */}
            {/* 🆕 **و٢٢px لا ١٨** (D-297، طلبُ أحمد: «العنوان يكون بالخط
                الكبير في المكان الأحمر بحيث يوضح»): **المساحةُ إلى جانب
                الملصق كانت فارغةً وقد فرغ ركنُها الأعلى بحذف السهم** —
                **واسمُ العمل هو سببُ الصفحة، فيأخذها.** */}
            {typeof avg === "number" && typeof count === "number" && count > 0 && (
              /* 🆕 **وسطرٌ بارتفاع نصِّه لا أكثر** (D-303، البند (ب) من
                 مخرجَي D-297): **`leading-none` وبلا هامشٍ علويّ** —
                 **الخطُّ نفسُه والرقمُ نفسُه، وإنما سقط الفراغُ الذي لا
                 يحمل معنًى.** */
              <p
                className="text-[12px] font-bold leading-none text-accent tabular-nums"
                title={ratingLabel}
              >
                ★ <span dir="ltr">{avg}</span>
                <span className="font-normal text-white/70"> ({count})</span>
              </p>
            )}
            {meta}
            {/* ⚖️ 🆕 **وسطرُ «نقاش مسلسل …» حُذف** (D-304، شطبَه أحمد في
                اللقطة نفسِها). **وُلد في D-286 حين كان في الغلاف فراغٌ
                يُملأ** — **واليوم الاسمُ يملؤه، فصار السطرُ يقول ما تقوله
                الصفحةُ كلُّها** (D-223/D-222: سطرٌ لا يضيف خبراً ضجيج).
                **وسقط معه `sub` من التوقيع** لأن قارئَه الوحيد سقط
                (D-214). */}
          </div>
        </Link>
      </div>
    </header>
  );
}

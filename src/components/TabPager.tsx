    const sides = [...track.children] as HTMLElement[];
    const sign = rtl ? 1 : -1;
    const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    /** **الشريطُ يمشي مع اللوحة** — رقمٌ واحدٌ يقرؤه رأسُ التبويبات */
    const publish = setTabDrag;


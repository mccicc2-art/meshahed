"use client";

import { useState } from "react";
import { getDict, type Locale } from "@/lib/i18n";
import { dirOf, alignOf } from "@/lib/dir";

/**
 * 🆕 **نصٌّ سطرٌ واحدٌ ثم يُوسَّع** (D-304، طلبُ أحمد: «الوصف تحت يكون
 * سطر واحد ونهايته زرّ المزيد، واللي يبغى يقراه كامل يوسّعه، وإذا توسّع
 * فيه زرّ تقليل»).
 *
 * ================= ولماذا زرٌّ هنا وقد رُفض من قبل =================
 *
 * **كان الوصفُ ثلاثةَ أسطرٍ تُقصّ بلا زرّ** (D-284)، **والحجّةُ يومَها
 * أن صفحةَ العمل على بُعد ضغطةٍ من الملصق فلا حاجةَ لبابٍ ثانٍ**
 * (D-266). **وقد سقطت الحجّةُ اليوم بأمرين معاً:** الوصفُ صار **سطراً
 * واحداً** — **وسطرٌ واحدٌ لا يعرّف عملاً، هو إعلانُ وجودِ نصٍّ لا
 * النصّ** — **وصفحةُ العمل ليست هي هذا النصّ** بل صفحةٌ أخرى بتبويباتها.
 * **فالمقارنةُ صارت بين ضغطةٍ تفتح سطرين هنا وضغطةٍ تنقلك من الغرفة.**
 *
 * ================= وثلاثةُ قراراتٍ صغيرة =================
 *
 * **١) ولا `<details>`**: عنصرُ النظام يجرّ مثلّثَه وخطَّ تركيزه وسلوكَه
 * **ولا يرث الثيم** — وهو نفسُ حجّة D-016 في `input[type=file]`.
 * **٢) والزرُّ في آخر السطر لا تحته**: **سطرٌ ثانٍ لكلمةٍ واحدة يضاعف
 * ارتفاعَ ما جئنا نختصره.** **والقصُّ بـ`line-clamp` لا بعدِّ الحروف** —
 * **عدُّ الحروف يكذب في العربية والإنجليزية بمقدارين مختلفين** (D-282).
 * **٣) والاتّجاهُ من النصّ لا من الواجهة** (D-282): TMDB تُرجع النبذةَ
 * بلغة القارئ حين تتوفّر، **فقد تعود عربيةً في واجهةٍ إنجليزية.**
 */
export function ExpandableText({
  text,
  locale,
  lines = 1,
}: {
  text: string;
  locale: Locale;
  /** **عددُ السطور وهو مطويّ** — واحدٌ افتراضاً، **والموسَّعُ بلا حدّ** */
  lines?: number;
}) {
  const t = getDict(locale);
  const [open, setOpen] = useState(false);
  const dir = dirOf(text);

  return (
    <p
      dir={dir}
      className={`mt-2 text-[13px] leading-relaxed text-muted ${alignOf(text)} ${
        open ? "" : lines === 1 ? "line-clamp-1" : "line-clamp-3"
      }`}
    >
      {text}{" "}
      {/* **والزرُّ داخل الفقرة**: يتبع آخرَ كلمةٍ في الحالتين — **وهو ما
          يجعله يُقرأ نهايةَ النصّ لا عنصراً مستقلّاً** (D-288: صفٌّ واحد).
          ⚠️ **و`whitespace-nowrap`** لئلّا تنكسر الكلمةُ وحدَها سطراً
          فتُفسد وعدَ «سطرٍ واحد». */}
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        aria-expanded={open}
        className="whitespace-nowrap align-baseline text-[12px] font-bold text-accent hover:underline"
      >
        {open ? t.showLess : t.showMore}
      </button>
    </p>
  );
}

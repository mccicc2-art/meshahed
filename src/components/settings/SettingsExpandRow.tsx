"use client";

import { Icon, type IconName } from "../Icon";
import { SettingsRow } from "./SettingsRow";

/**
 * 🆕 **صفٌّ يتوسّع في مكانه بدل ورقةٍ تصعد من الأسفل** (D-569، طلبُ
 * أحمد بلقطتين: شطبَ الورقةَ السفليّة كلَّها وكتب «هذي الصفحة من تحت
 * ما عاد أبغاها — أبغى اللي يختار تظهر تحتها تمتدّ في نفس الصفحة»،
 * ورسم مستطيلاً على الفراغ تحت البطاقة).
 *
 * ================= الحجّة =================
 *
 * **والفراغُ الذي رسمه هو الدليل**: صفحةُ المظهر أربعةُ صفوفٍ في أعلى
 * الشاشة **وتحتها ثلثا الشاشة سوادٌ فارغ** — **ثمّ يُغطّى ذلك الفراغُ
 * بورقةٍ تصعد لتعرض أربعةَ خيارات.** **ورقةٌ تحجب صفحةً فارغةً لتقول
 * ما كان يسع الفراغَ نفسَه.**
 *
 * **وثمنُ الورقة يُدفع ثلاث مرّات**: تُفتح، تُقرأ، ثمّ تُغلق —
 * **وتُخفي في أثناء ذلك الصفَّ الذي جئتَ تغيّره** فلا ترى أثرَ
 * اختيارك حتى تغلقها. **والتوسّعُ يُبقي كلَّ شيءٍ في مكانه**: الصفُّ
 * فوق خياراته، وقيمتُه في طرفه تتبدّل تحت عينك.
 *
 * ⚠️ **وليست كلُّ ورقةٍ تسقط**: **هذا للاختيار الواحد** (لغة · ثيم ·
 * حجم) — **والمتعدّدُ الذي يُبحث فيه** (لغات المحتوى · الأنواع)
 * **والسحبُ والتأكيدُ تبقى أوراقاً**: **قائمةٌ من ستّين لغةً بحقل بحثٍ
 * لا تتوسّع داخل بطاقة**، وتوسيعُها يدفع ما تحتها شاشتين.
 *
 * ⚠️ **والسهمُ يقول الحالة**: يشير إلى الطرف مغلقاً، **وينزل مفتوحاً**
 * — **والدوران هو نفسُه دورانُ سهم `SettingsRow`** فلا رمزَ ثانٍ.
 */
export function SettingsExpandRow({
  icon,
  title,
  value,
  open,
  onToggle,
  children,
}: {
  icon?: IconName;
  title: string;
  /** القيمةُ الحاليّة في الطرف — تتبدّل تحت العين لأن الصفَّ لا يُحجب */
  value?: string;
  open: boolean;
  onToggle: () => void;
  children: React.ReactNode;
}) {
  return (
    /* **الصفُّ ولوحُه ابنٌ واحدٌ للبطاقة** — و`divide-y` في
       `SettingsGroup` ترسم الخيطَ بين الصفوف، **فلو كانا ابنَين
       لانفصل اللوحُ عن صفِّه بخطٍّ يقول إنهما شيئان.** */
    <div>
      <SettingsRow
        icon={icon}
        title={title}
        value={value}
        onClick={onToggle}
        expanded={open}
        trailing={
          <Icon
            name="chevron-down"
            size={18}
            className={`shrink-0 text-muted transition-transform duration-200 ${
              open ? "" : "-rotate-90 rtl:rotate-90"
            }`}
          />
        }
      />
      {open && <div className="px-3.5 pb-3.5">{children}</div>}
    </div>
  );
}

"use client";

import Link from "next/link";
import { Avatar } from "./Avatar";

/**
 * صورة الشريط العلوي.
 *
 * **تظهر في كل الصفحات بلا استثناء** — وهي مدخلُ المستخدم إلى ملفّه
 * وإعداداته على الشاشة الواسعة. **وكانت تختفي في الرئيسية** يومَ كانت
 * ترويسةُ الحساب تعرض الصورةَ كبيرةً على غلافها؛ انظر حجّةَ سقوط الاستثناء
 * في جسد المكوّن.
 *
 * ⚖️ 🆕 **ووجهتُها صارت الإعداداتِ الرئيسية** (D-571، طلبُ أحمد:
 * «إذا ضغطت على الصورة من أيّ مكان يوديني على الإعدادات الرئيسية»).
 *
 * **وكانت `/profile/edit`** — **بابٌ واحدٌ من أحدَ عشرَ باباً في
 * الإعدادات**، **وصورةٌ في شريطٍ يرافقك في كلِّ صفحةٍ يجب أن تفتح
 * الفهرسَ لا ورقةً منه.** **ومن أراد تعديلَ ملفّه يجده في السطر
 * الأوّل من الفهرس.**
 *
 * 🔑 **وثلاثةُ أبوابٍ لثلاث صور — لكلٍّ معناه** (D-571):
 * **صورةُ الشريط ← الإعدادات** (رفيقةُ كلِّ صفحة، فوجهتُها عامّة) ·
 * **صورةُ الرئيسية ← ملفّي العامّ** (هي ترحيبٌ بي، فتُريني نفسي كما
 * يراني الناس) · **صورةُ الملفّ ← تعديلُ ملفّي** (أنا فيه أصلاً،
 * فالباقي أن أغيّره).
 */
export function NavAvatar({
  src,
  name,
  title,
  alt,
  ariaLabel,
}: {
  src: string | null | undefined;
  name: string;
  title: string;
  alt: string;
  ariaLabel: string;
}) {
  /* ⚖️ 🆕 **وسقط استثناءُ الجذر** (D-434): كانت تختفي في الرئيسية لأن
     ترويسةَ الحساب هناك تعرض الصورةَ كبيرةً على الغلاف — **وقد غادرت
     الترويسةُ إلى الملفّ العامّ**، **فبقي استثناءٌ يحرس شيئاً لم يعد
     موجوداً**، وثمنُه أن مستخدمَ الشاشة الواسعة لا يجد باباً إلى ملفّه
     ولا إلى إعداداته في أكثر صفحاتِ التطبيق زيارةً.
     **وصورةُ الترحيب في `HomeHeader` `md:hidden`** — **صورةٌ واحدةٌ في
     كلّ عرض** (قاعدة ٦). */

  return (
    <Link
      href="/profile/settings"
      prefetch={false}
      title={title}
      aria-label={ariaLabel}
      /* 🆕 **صندوقُها ٤٤ وصورتُها ٣٦** (D-541 ثمّ D-543): **الجرسُ والظرفُ
         صندوقُهما ٤٠**، **وخانةٌ أخيرةٌ أضيقُ تسحب ما قبلها إلى الطرف**
         — فيقفز الظرفُ عند كلِّ انتقالٍ من الرئيسية وإليها.
         **والحلقةُ `ring` لا تدخل الحساب** (ظلٌّ لا هامش) — فالمقاسُ
         الظاهرُ باقٍ كما كان. */
      className="shrink-0 grid place-items-center w-11 h-11 rounded-full ring-2 ring-transparent hover:ring-accent transition"
    >
      <Avatar src={src} name={name} size={36} alt={alt} />
    </Link>
  );
}

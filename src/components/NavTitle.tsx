"use client";

import { usePathname } from "next/navigation";
import { getDict, type Locale } from "@/lib/i18n";

/**
 * **اسمُ الصفحة في منتصف الشريط العلويّ** (D-258، طلبُ أحمد: «اخفِ
 * الكلمات في الشريط السفلي واكتبها فوق في منتصف السطر، ما عدا Home»).
 *
 * ================= لماذا نُقل الاسمُ ولم يُحذف =================
 *
 * الشريطُ السفليّ كان يحمل أيقونةً واسماً لكل تبويب — **والاسمُ هناك
 * يقول شيئين معاً**: «إلى أين يودّي هذا الزرّ» و«أين أنت الآن». **والثاني
 * تقوله الأيقونةُ الصفراء وحدها**، فبقي الاسمُ يشرح أربعةَ أزرارٍ لا
 * تُضغط إلا بعد أن تُتعلَّم مرّة. **وخمسُ كلماتٍ في صفٍّ عرضُه شاشةُ
 * هاتف تُقصّ وتضيق ولا تُقرأ.**
 *
 * **وفوق، الاسمُ يقول شيئاً واحداً: أين أنت.** وهو موضعُه في كل تطبيقٍ
 * له عُرف (D-150) — والأيقونةُ تبقى تحت تقول إلى أين.
 *
 * **و«الرئيسية» بلا اسمٍ بطلبه** — وهو محقّ: الرئيسيةُ تُعرف بغلافها
 * واسمِك عليه، **وعنوانٌ فوق غلافٍ يحمل اسمَك يكرّر ما قرأته للتوّ**
 * (D-224).
 *
 * ================= ومطابقةٌ تامّة لا بادئة =================
 *
 * ⚠️ **الخريطةُ بالمسار كاملاً لا بـ`startsWith`**: الشريطُ السفليّ ينسب
 * `‎/show/…` و`‎/movie/…` إلى «مكتبتي» **ليضيء مرساةً** — وذلك صوابٌ
 * هناك وكذبٌ هنا: **صفحةُ فيلمٍ ليست «مكتبتي»**، ولها ترويستُها الغلافية
 * باسم العمل. **فما لا يُطابِق يبقى بلا عنوان** — والصفحاتُ العميقة تحمل
 * أسماءها بنفسها (`ThreadTopBar` · `DetailTopBar` · ترويسةُ الغلاف).
 */
const TITLES: Record<string, "library" | "news" | "people" | "search"> = {
  "/library": "library",
  "/news": "news",
  "/people": "people",
  "/search": "search",
};

export function NavTitle({ locale }: { locale: Locale }) {
  const pathname = usePathname();
  const t = getDict(locale);
  const key = TITLES[pathname];
  if (!key) return null;

  const label =
    key === "library"
      ? t.navLibrary
      : key === "news"
        ? t.navNews
        : key === "people"
          ? t.navPeople
          : t.navSearch;

  return (
    /* **مركزةٌ بالمطلق لا بالتدفّق**: طرفا الشريط غيرُ متساويي العرض
       دائماً (شارةُ عددٍ تظهر فتزيد طرفاً)، **وعنوانٌ يتحرّك مع شارةٍ
       ليس في المنتصف**. والحشوُ الجانبيّ يمنع تداخلَه مع الأيقونات،
       و`truncate` تقصّه قبل أن يزحف.

       **و`pointer-events-none` لأنه نصٌّ لا زرّ** — ولا يبتلع لمسةً
       قاصدةً لِما تحته. **ويُخفى على الشاشة الواسعة** حيث `NavLinks`
       تقول أين أنت بالكلمة نفسِها (D-002: لا عائلةَ ثانية للمعنى). */
    <span
      className="md:hidden pointer-events-none absolute inset-0 flex items-center justify-center px-28"
      aria-hidden
    >
      <span className="truncate text-[15px] font-bold leading-none">{label}</span>
    </span>
  );
}

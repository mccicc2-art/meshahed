import type { Locale } from "@/lib/i18n";
import { MessagesLink } from "./MessagesLink";
import { SignalsLink } from "./SignalsLink";

/**
 * **طرفُ الشريط العلويّ — مقاسٌ واحدٌ ومسافةٌ واحدةٌ في كلِّ صفحة**
 * (D-541، بلاغُ أحمد بلقطتين: «مكان الرسالة والجرس لازم يطابق موقعها في
 * كل الصفحات، بحيث في الانتقال ما يحصل عدم توازن وكل وحدة موقع»).
 *
 * ================= وهذا ثمنُ D-536 يُدفع لا يُبرَّر =================
 *
 * **حين عاد للرئيسية شريطُها الخاصّ** (بطلبه، وبثمنٍ مكتوبٍ في موضعه)
 * **صار للتطبيق صفّا أدواتٍ لا واحد** — **وكلٌّ منهما يكتب مسافتَه
 * بيده**: الرئيسيةُ `gap-0.5` والشريطُ العامّ `gap-2`، **وآخرُ عنصرٍ
 * هناك صورةٌ صندوقُها ٣٦ وهنا ترسٌ صندوقُه ٤٠**. **فالجرسُ يقفز ٥px
 * والظرفُ ٣ في كلِّ تنقّل** — **وهو بالضبط ما اشتكى منه، وبالضبط ما
 * كانت D-502 تحرسه.**
 *
 * **والعلاجُ ليس توحيدَ الشريطين** (ذاك قرارٌ اتُّخذ ونُقض بكلمته)
 * **بل توحيدُ الصفِّ الذي يشتركان فيه**: **جرسٌ وظرفٌ وخانةٌ أخيرة** —
 * **والمسافةُ والمقاسُ يُكتبان هنا مرّةً واحدة.** **وسلسلةُ أصنافٍ
 * منسوخةٌ في ملفّين علامةُ عيبٍ لا أسلوب** (D-145).
 *
 * ⚠️ **والخانةُ الأخيرة تختلف عمداً**: صورةُ الحساب في الصفحات، وترسُ
 * الإعدادات في الرئيسية — **وهو فرقُ معنًى اختاره المالك** (D-536).
 * **والمشتركُ موضعُها لا هويّتُها**: **كلُّ ما يدخل هذه الخانة صندوقُه
 * ٤٤×٤٤** — **وإلّا انزاح ما قبله.**
 */
export function HeaderTrailing({
  unreadSignals,
  unreadShares,
  locale,
  children,
}: {
  unreadSignals: number;
  unreadShares: number;
  locale: Locale;
  /** الخانةُ الأخيرة — **صندوقُها ٤٤×٤٤ أو انكسر التطابق** (D-543) */
  children: React.ReactNode;
}) {
  /* 🆕 والفراغُ بينها سقط (D-620: «قرّبها من بعض») — الصناديقُ ٤٠ متلاصقة */
  return (
    <div className="flex items-center">
      {/* 🆕 **الظرفُ قبل الجرس** (D-618، توزيعُ أحمد المرسوم) — والقلبُ
          هنا في المصدر الواحد فيتحرّك الشريطان معاً ولا ينكسر تطابقُ
          المواضع بين الصفحات (قاعدةُ D-541 نفسُها) */}
      <MessagesLink unread={unreadShares} locale={locale} />
      <SignalsLink unread={unreadSignals} locale={locale} />
      {children}
    </div>
  );
}

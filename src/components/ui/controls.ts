/**
 * خانة المقسّم — **شريطٌ سميكٌ بلون الثيم، جالسٌ على الخطّ لا طائرٌ فوقه**.
 *
 * ================= تاريخُ هذا الشريط، ونقضٌ مسجَّل =================
 *
 * **٩ أغسطس:** كان ثلاثةَ بكسلاتٍ بحوافّ مستديرة **يطفو فوق الخطّ الرمادي
 * بفجوة**، فقرأه أحمد **خطّاً ثانياً** لا علامةَ اختيار: «لا تحط خط ثاني،
 * خلها نفس الخط هو الي يسير جزء منه أصفر». فصار **بكسلاً واحداً** بسُمك
 * الحدّ نفسه.
 *
 * **١٢ أغسطس — ونقضٌ بطلبه، ومعه صورةٌ مرجعية:** «إذا اخترت تبويب احتاج
 * خط تحت بلون الثيم **مثل ما كنا مسوين قبل**». والبكسلُ الواحد كان أضعف
 * من أن يُرى على الجوال — **علامةُ اختيارٍ لا تُرى ليست علامة** (نفس درس
 * D-142 في زرّ «غير مهتم»).
 *
 * **والفرقُ الذي يمنع عودة شكوى ٩ أغسطس هو الموضع لا السُّمك:** الشريطُ
 * القديم كان يطفو **فوق** الخطّ بفجوةٍ فبدا سطراً مستقلاً؛ وهذا يجلس عند
 * `-bottom-px` **فيلامس الخطّ ويغطّيه** — والخطُّ الرمادي يستمرّ يمنةً
 * ويسرة، فيُقرأ **جزءاً من الخطّ صار سميكاً وأصفر** لا خطّاً ثانياً.
 * **وهو حرفياً ما تعرضه صورتُه المرجعية.**
 *
 * والاستدارةُ من أعلى وحدها (`rounded-t-full`): أسفلُه ملتصقٌ بالحدّ فلا
 * معنى لاستدارةٍ لا تُرى، واستدارةُ الطرفين معاً هي ما جعله يبدو «قطعةً»
 * منفصلة في المرّة الأولى.
 *
 * وشرطُ نجاحه أن يحمل **صفُّ التبويبات** الحدَّ السفليّ لا حاويةٌ أبعد
 * منه: لو كان الحدّ أسفل الرأس كلّه لطفا الأصفر فوقه بفجوة. `PageTabs`
 * يضمن ذلك. متماثلٌ في RTL/LTR.
 *
 * والفاصل الرأسيّ عنصرٌ زائفٌ (`before`) على كل خانةٍ عدا الأولى، مقصوصٌ
 * من أعلى وأسفل فلا يلمس الخطّ الأفقيّ السفليّ. يُوضع على الحافة البادئة
 * (`start`) فينقلب تلقائياً في RTL.
 *
 * `pad=false` لمن يحتاج حشواً خاصاً: تمرير `px-2` في `className` لا يكفي —
 * الغلبة في CSS لترتيب التوليد لا لترتيب النصّ. فمن يريد حشوه يمرّر `false`.
 */
export function segmentedItem(active: boolean, className = "", pad = true) {
  const rule =
    "before:pointer-events-none before:absolute before:inset-y-2 before:start-0 before:w-px before:bg-[color:var(--divider)] first:before:hidden";
  return `${pad ? "px-4 pt-2 pb-3 text-14 " : ""}relative font-semibold whitespace-nowrap transition-colors ${rule} ${
    active
      ? "text-foreground after:pointer-events-none after:absolute after:-bottom-px after:inset-x-0 after:h-[3px] after:rounded-t-full after:bg-accent"
      : "text-muted hover:text-foreground"
  }${className ? ` ${className}` : ""}`;
}

export type ChipSize = "sm" | "md";

const CHIP_SIZE: Record<ChipSize, string> = {
  sm: "px-2.5 py-1 text-12",
  md: "px-3.5 py-2 text-sm",
};

export function chipClass(active: boolean, size: ChipSize = "md", className = "") {
  return `${CHIP_SIZE[size]} rounded-full border font-semibold whitespace-nowrap transition ${
    active
      ? "bg-accent text-[color:var(--on-accent)] border-accent"
      : "bg-surface text-muted border-border hover:text-foreground hover:border-accent/50"
  }${className ? ` ${className}` : ""}`;
}


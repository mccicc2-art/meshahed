/**
 * جسمُ الورقة الذي يُمرَّر — والنصف المنسيّ منه هو العطل (D-157).
 *
 * لوحُ الورقة `flex flex-col` بسقفٍ (`max-h-[80svh]`) و`overflow-hidden`.
 * وابنٌ مرن **افتراضُه `min-height:auto`**، أي أنه يرفض أن يصغر تحت ارتفاع
 * محتواه. فقائمةٌ طويلة تجعل الجسم أطول من السقف، **فلا يصير قابلاً
 * للتمرير أصلاً** — واللوح يقصّ الفائض بلا أي طريقةٍ لبلوغه.
 *
 * وفي الورقة السفلية (`items-end`) يخرج الفائض من **أعلاها**: الترويسة
 * وزرّ الإغلاق يصعدان خلف شريط المتصفّح. وهذا نصّ بلاغ أحمد حرفياً —
 * «قائمة الإشعارات طالعة فوق» — مرّتين، في ٩ و١١ أغسطس.
 *
 * **و`overflow-y-auto` وحده لا يكفي، و`svh` وحدها لا تكفي:** إصلاح ٩ أغسطس
 * أضاف الحاوية وأنزل السقف إلى `80svh` فعالج ما ظهر، **وترك السبب**.
 * `flex-1 min-h-0` هو ما يجعل الجسم يقبل الانكماش فيملك تمريره.
 *
 * ولماذا وصفةٌ لا تكرار: السلسلة كانت منسوخةً في **اثني عشر** موضعاً،
 * **خمسةٌ منها فقط تذكر النصف الحاسم**. وهذا نصّ قاعدة D-145: سلسلةُ
 * أصنافٍ منسوخةٌ في ملفّين علامةُ عيبٍ لا أسلوب.
 */
export const sheetScroll = "flex-1 min-h-0 overflow-y-auto overscroll-contain";

import { getUnreadSignals } from "@/lib/data";

/**
 * نقطةُ «هناك جديدٌ هناك» على تبويب المجتمع في الشريط السفلي
 * (طلب أحمد ١١ أغسطس، ومرجعُه تويتر: «حاطين نقطة زرقاء عشان توجه الشخص
 * أن فيه إشعار أو جديد في الصفحة»).
 *
 * **مكوّنُ خادمٍ يُمرَّر عقدةً جاهزة** — نفس نمط `listsExtra` في المكتبة
 * (D-063): الشريط عميل، والعدّ يحتاج القاعدة. ولو صعد النداء إلى
 * `layout` لانتظرته **كلُّ صفحةٍ في التطبيق** قبل أوّل بايت — والترويسة
 * وُضعت خلف `Suspense` لهذا السبب بعينه. فهنا يُبثّ خلف `Suspense`
 * أيضاً: تُرسم الصفحة، ثم تصل النقطة إن كان لها ما تقوله.
 *
 * **ولونها لون الهوية لا أزرق.** نقطةُ تويتر زرقاء لأن **الأزرق هويّتُه**؛
 * وترجمتُها الصادقة هنا هي أصفر لوبز — وهو أيضاً لون شارة غير المقروء في
 * الوارد والتبويبات، فلا لغةَ تنبيهٍ ثانية (قاعدة ٦).
 *
 * **ولا تظهر على التبويب المفتوح:** «هناك جديدٌ **هناك**» جملةٌ لا معنى
 * لها وأنت واقفٌ فيه. الشريط هو الذي يُسقطها، لا هذا الملف.
 */
export async function NavSignalDot() {
  const n = await getUnreadSignals();
  if (!n) return null;
  return (
    <span
      aria-hidden
      className="absolute top-0.5 end-[22%] h-2 w-2 rounded-full bg-accent ring-2 ring-[color:var(--background)]"
    />
  );
}

"use client";

import { useRef } from "react";
import { setHomeView } from "@/lib/actions";
import { getDict, type Locale } from "@/core/i18n";
import { tap } from "@/lib/haptics";
import { flashError } from "@/lib/toast";
import type { HomeView } from "@/core/homePrefs";
import { useHomeView } from "./HomeViewProvider";
import { Icon } from "./Icon";

/**
 * مبدّلُ وضع عرض الرئيسية (D-434).
 *
 * **والزرُّ يحمل اسمَ الوجهة لا اسمَ الحال** — «مختصر» وأنت في البصريّ،
 * و«بصري» وأنت في المختصر. **وهو عرفُ المبدّلات ذات الحالتين**: زرٌّ
 * يكتب حالتَك الراهنة يُقرأ لافتةً لا فعلاً، **فيضغطه من أراد ما هو فيه
 * أصلاً.**
 *
 * **والحفظُ في الحساب لا في الجهاز** (طلبُ أحمد: «عند العودة للتطبيق
 * يظهر آخر View اختاره المستخدم»): كوكيٌّ يضيع بتبديل الجهاز أو المتصفّح،
 * **والاختيارُ صفةُ حسابٍ لا صفةُ متصفّح.**
 *
 * ⚖️ 🆕 **والتبديلُ صار محلّيّاً بحتاً** (جولة ٢٢ أغسطس): **كان
 * `await setHomeView` ثم `router.refresh()`** — **رحلةُ خادمٍ كاملة
 * لتغيير شكل**، **ورسمتان لا واحدة** (`revalidatePath` في الفعل ثم
 * التحديث في الزرّ). 📏 **المقيسُ في الإنتاج**: ١١٠ ك.ب و**خمسُ رحلات**
 * لضغطةٍ واحدة. **الآن**: `setView` يبدّل الشجرةَ المرسومةَ سلفاً
 * (`ByHomeView`) **في الإطار نفسِه**، والحفظُ يمشي خلفَه.
 *
 * ⚠️ **والزرُّ لا يُعطَّل أثناء الحفظ**: لا شيءَ ينتظره — **وزرٌّ
 * معطَّلٌ بعد ضغطةٍ فوريّةٍ يقول إنّ شيئاً يجري ولا شيءَ يجري.**
 *
 * 🔑 **وإن سقط الحفظ: الشكلُ يبقى ولا يُرجَع** — **إرجاعُ الرسم تحت
 * إصبع من ضغط للتوّ عقوبةٌ على عطلٍ ليس منه**، **والرسالةُ تقول الثمنَ
 * صراحةً**: يعود الوضعُ السابق عند إعادة الفتح (`errViewSave`).
 */
export function HomeViewSwitch({
  locale,
}: {
  locale: Locale;
}) {
  const t = getDict(locale);
  const { view: current, setView } = useHomeView();

  /* **سلسلةُ وعودٍ لا نداءٌ متوازٍ**: ضغطتان متلاحقتان تكتبان العمودَ
     نفسَه، **والمتوازيتان قد تصلان مقلوبتين فيُحفظ غيرُ ما يُرى.** */
  const queue = useRef<Promise<unknown>>(Promise.resolve());

  const next: HomeView = current === "visual" ? "compact" : "visual";
  /* ⚖️ 🆕 **والكلمةُ سقطت وبقي الرمز** (D-589، بلاغُ أحمد بلقطة: «هذي
     خلّها رمز فقط بدون نص») — **نقضُ شطرِ «الزرُّ يحمل اسمَ الوجهة» من
     D-434 بيد صاحبه**: **الرمزُ ما زال يحمل الوجهةَ لا الحال** (شبكةٌ
     للبصريّ وقائمةٌ للمختصر)، **والاسمُ الكامل في `aria-label`
     و`title`** — فالعُرفُ باقٍ والكلمةُ وحدَها غادرت. */
  const label = next === "compact" ? t.viewCompact : t.viewVisual;

  function switchTo() {
    tap(8);
    /* الرسمُ أوّلاً — الشجرتان مرسومتان أصلاً فالتبديلُ اختيارُ فرع */
    setView(next);
    /* ثمّ الحفظُ في `profiles.home_prefs` خلفَ الرسم — **وهو ما يجعل
       الاختيارَ يعبر الأجهزةَ وإعادةَ الفتح** */
    queue.current = queue.current
      .catch(() => {})
      .then(() => setHomeView(next))
      .catch(() => flashError(t.errViewSave));
  }

  return (
    <button
      type="button"
      onClick={switchTo}
      aria-label={`${t.viewSwitchAria} — ${label}`}
      title={label}
      /* 🆕 **زاويةٌ من سلّم البطاقات لا قرصٌ كامل** (D-451، طلبُ أحمد:
         «الزوايا خلّيها مثل التصميم»). **وبطاقةُ الأرقام تحته مباشرةً
         `rounded-2xl`** — **وقرصٌ فوق بطاقةٍ في صفَّين متلاصقين لغتا
         استدارةٍ في ثلاثة سنتيمترات** (القاعدة ٣: سلّمُ زوايا واحد).
         ⚠️ **ولا قيمةَ جديدة**: نفسُ `2xl` المكتوبة تحته بالضبط.

         🆕 ⚖️ **والوزنُ ٦٠٠ لا ٧٠٠** (D-459): **كان آخرَ ٧٠٠ عند مقاس
         ١٢ في الصفحة** — **ووزنٌ لعنصرٍ واحدٍ استثناءٌ لا درجة**،
         والزرُّ له حدُّه وسطحُه ورمزُه يحملونه.

         🆕 **والخطُّ ١٢ والرمزُ ١٥** («صغّر الخط… وكومباكت») —
         **والارتفاعُ ٤٤ كما هو**: قاعدتُك «اجعل مناطق الضغط مناسبة
         للجوال»، **وخطٌّ أصغر لا يعني هدفاً أصغر**. الذي ضاق هو الحشو
         فضاق الزرُّ عرضاً — وهو ما يُرى. */
      /* ⚖️ 🆕 **والحلّةُ قصُرت ٤٤ → ٤٠، وهدفُ اللمس بقي ٤٤** (D-550،
         طلبُ أحمد: «الإطار في كلمة compact صغّر ارتفاعه شويّ مع عدم
         المساس بحجم الخط»).

         🔑 **وصندوقان لا واحد، عمداً**: **الزرُّ نفسُه يبقى ٤٤ شفّافاً**
         — **وهو قاعدتُك التي كتبتَها اليوم بنفسك في D-543** («مساحة
         اللمس ٤٤×٤٤»)، **ولا تُنقض بعد ساعات لأجل أربعة بكسلات** —
         **والحلّةُ المرئيّةُ داخله ٤٠**: الحدُّ والسطحُ والزاويةُ
         عليها هي. **فما رآه أحمد قصُر، وما تلمسه إصبعُه لم يتغيّر.**

         ⚠️ **والخطُّ لم يُمسّ**: `text-12` والرمزُ ١٥ كما هما بالضبط
         (شرطُه الصريح) — **والذي ضاق هو الحشوُ الرأسيّ وحدَه.**

         ⚖️ **ثمّ سقط الإطارُ وحدَه ونزلت الحلّةُ إلى ٣٦** (طلبُه
         الثاني: «احذف الإطار فقط منها وصغّر الارتفاع قليلاً»):
         **السطحُ والزاويةُ باقيان** — **هو قال «الإطار فقط»** —
         **وهدفُ اللمس ٤٤ كما هو.**

         ⚠️ **وسقط معه تمويهُ الحدّ**: `group-hover:border-accent/50`
         كان يلوّن حدّاً لم يعد موجوداً. **ولا يُخترع له بديلٌ**
         (وميضُ سطحٍ أو ظلّ) — **صنفٌ جديدٌ لحالةِ مؤشّرٍ لا يراها
         الجوّالُ أصلاً** (القاعدة ٣)، **والضغطةُ لها `active:scale-95`
         وهي التي تُحسّ باليد.** */
      className="shrink-0 grid place-items-center w-10 h-10 rounded-full hover:bg-surface-2 active:scale-95 transition"
    >
      {/* ⚖️ 🆕 **والحلّةُ سقطت والزرُّ صعد إلى صفِّ الأيقونات** (D-618،
          توزيعُ أحمد المرسوم): جيرانُه الظرفُ والجرسُ والترسُ كلُّهم
          رمزٌ عارٍ في ٤٤ — **وحلّةُ سطحٍ وحيدةٌ بينهم كانت ستقرأ
          زرّاً من عائلةٍ ثانية** (القاعدة ٣). **والرمزُ ٢٤ كمقاسهم
          حرفاً** (عقدُ D-543)، **ولونُ الهوية باقٍ يقول إنه مبدّلُك
          لا باباً عامّاً.** والرمزُ ما زال يصف الوجهةَ لا الحال. */}
      {/* ⚖️ 🆕 ٢٤ → ٢٠ (D-619) ثمّ ١٨ والصندوقُ ٤٠ مع الصفِّ كلِّه (D-620) */}
      <Icon
        name={next === "compact" ? "list" : "grid"}
        size={18}
        strokeWidth={2}
        style={{ color: "var(--accent)" }}
      />
    </button>
  );
}

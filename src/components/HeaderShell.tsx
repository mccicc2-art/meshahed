"use client";

import { usePathname } from "next/navigation";
import { hidesAppHeader, hidesAppHeaderOnMobile } from "@/core/chromeRules";

/**
 * غلاف الشريط العلوي.
 *
 * يخفيه في الرئيسية على الجوال وحده. السبب: هناك لا يحمل الشريط إلا أيقونة
 * التطبيق — الروابط في الشريط السفلي، والبحث مخفيّ على الجوال، والصورة
 * انتقلت إلى ترويسة الصفحة. أربعة وستون بكسلاً لأيقونةٍ واحدة، والغلاف
 * تحتها ينتظر. على الشاشات الواسعة يبقى كما هو لأنه يحمل الروابط والبحث.
 *
 * ⚠️ **`contents` لا `block` — وهذا ليس تفصيلاً في الشكل.**
 *
 * العنصر `sticky` يلتصق داخل صندوق **أبيه** لا داخل الشاشة. وكان هذا الغلاف
 * `div` عادياً ارتفاعه ارتفاع الشريط نفسه (٦٥ بكسلاً)، فما إن يمرّر
 * المستخدم ٦٥ بكسلاً حتى يخرج الأب من الشاشة ويخرج الشريط معه — أي أن
 * `sticky top-0` في `Navbar` كان معطَّلاً في **كل** صفحة، ويُلحَظ في
 * الطويلة منها وحدها (صفحة العمل، اكتشف، المكتبة).
 *
 * و`display: contents` يُلغي صندوق الغلاف ولا يُلغي أبناءه، فيعود أبو
 * الشريط هو `body` ويعود الالتصاق يعمل. الإخفاء على الجوال يبقى كما هو:
 * `display: none` يعمل فوق `contents` بلا تعارض.
 *
 * القاعدة العامة: **أي غلاف يُوضع حول عنصر `sticky` يجب أن يكون
 * `contents`، وإلا صار سقفاً لالتصاقه.**
 */
export function HeaderShell({
  children,
  signedIn = true,
}: {
  children: React.ReactNode;
  signedIn?: boolean;
}) {
  const pathname = usePathname();
  /* الإخفاء على الجوال للمسجَّل وحده (D-122): الجذر صار صفحة هبوطٍ للزائر
     غير المسجّل، وشريطُ الزائر يحمل مبدّل اللغة — إخفاؤه كان سيحبس زائر
     الجوال في لغةٍ واحدة بلا مخرج. أما المسجَّل فترويسةُ صفحته تُغني. */
  /* 🆕 **والإعداداتُ تُخفيه على كلِّ مقاس** (D-462): لها ترويستُها
     الداخليّة برجوعٍ واسمٍ وبحث — **وترويستان في شاشةٍ واحدة تجعلان
     سهمَي رجوعٍ وعنوانين**، ولا يعرف القارئُ أيَّهما يخرج به. */
  /* ⚖️ 🆕 **والشرطُ صار سؤالاً مركزيّاً** (D-493): `hidesAppHeader` في
     `chromeRules` — **ومسارٌ رابعٌ يُخفيه غداً يُكتب هناك مرّةً**، لا
     في هذا الملفّ وفي `BottomNav` وفي ثالثٍ يُنسى. **و`/stats` انضمّت
     لأن لها ترويستَها الداخليّة.** */
  /* ⚖️ 🆕 **وسقط إخفاءُ الرئيسية على الجوّال** (D-502، طلبُ أحمد
     بلقطتين: «لازم كلها في نفس المكان عشان وقت الانتقال بين الصفحات
     يطلع شكلها ثابت»).
     **حجّةُ D-122 كانت أن الشريط في الرئيسية لا يحمل إلا أيقونة** —
     **وقد صار يحمل الظرفَ وصورةَ الحساب**، **وترويسةُ الرئيسية كانت
     ترسمهما بنفسها في موضعين مختلفين بمقاسين مختلفين**، **فيقفز
     البابُ الواحدُ في كلِّ تنقّل** (D-150: العُرفُ يُبنى بالثبات).
     **فبقي شريطٌ واحدٌ في كلِّ مسار** — وصفُّ الرئيسية الخاصُّ حُذف من
     `HomeHeader`. */
  if (hidesAppHeader(pathname)) return null;

  /* ⚖️ 🆕 **والرئيسيةُ تخفيه على الجوّال وحدَه** (D-536) — **وهذا عودةُ
     D-122 بعد نقضها في D-502**، بطلب أحمد وبلقطته.
     **و`hidden md:contents` لا `return null`**: الشريطُ الواسع يحمل
     الروابطَ والبحث، **وحذفُه على اللوح يقطع التنقّل** — **و`display`
     يعمل فوق `contents` بلا تعارض** (حرفُ D-122).
     ⚠️ **والغلافُ يبقى `contents` على اللوح** وإلّا صار سقفاً لالتصاق
     `Navbar` كما في الحجّة أعلاه. */
  /* ⚖️ 🆕 **والإخفاءُ للمسجَّل وحدَه** (D-665، بلاغُ أحمد بلقطةٍ من
     جوّاله: «أوّل دخولٍ للموقع خيارُ اللغة غير ظاهر»).

     🔴 **وحجّةُ D-536 لم تُنقض، بل كانت أوسعَ من سببها**: الرئيسيةُ
     تُخفي الشريطَ لأن **`HomeHeader` ترسم بديلَه** (وردماركٌ وجرسٌ
     وظرفٌ وصورة) — **والزائرُ غيرُ المسجَّل لا `HomeHeader` له أصلاً**:
     الجذرُ عنده صفحةُ هبوطٍ بلا ترويسة، **فكان الإخفاءُ يحذف باباً بلا
     أن يضع بديلَه** — **وأوّلُ ما ضاع مبدّلُ اللغة**، فيقف الزائرُ في
     لغةٍ قد لا يقرؤها بلا مخرج.

     🔑 **وهو نصُّ D-122 عائداً بحرفه** — وقد كُتب في هذا الملفّ نفسِه:
     «شريطُ الزائر يحمل مبدّلَ اللغة — إخفاؤه كان سيحبس زائرَ الجوّال في
     لغةٍ واحدة بلا مخرج». **فعادت الرايةُ `signedIn` عاملةً بعد أن
     كانت `void`** — **ومعاملٌ يُقبل ولا يُقرأ هو نصفُ قاعدةٍ مكتوبةٍ
     ومنسيّة.**

     ⚠️ **وشكلُ المسجَّل لم يتبدّل بكسلاً**: حكمُ D-536 قائمٌ له. */
  if (signedIn && hidesAppHeaderOnMobile(pathname)) {
    return <div className="hidden md:contents">{children}</div>;
  }

  return <div className="contents">{children}</div>;
}

"use client";

/**
 * بوّابةُ الزائر (D-627 — المرحلة الثانية).
 *
 * القاعدة: التصفّحُ مفتوحٌ للجميع، وأفعالُ الكتابة — متابعة، تقييم،
 * ردّ — لأصحاب الحسابات. الخادمُ يحرسها أصلاً (`requireUser` في كلِّ
 * فعل)، وهذه الطبقةُ تجربةٌ لا أمن: بدل توست خطأٍ جافّ يرى الزائرُ
 * ورقةَ «سجّل دخولك للمتابعة» وفيها زرُّ الدخول نفسُه.
 *
 * **ونقطةُ الاعتراض واحدة لا اثنتان وأربعون**: كلُّ مكوّنات الكتابة
 * تُبلغ فشلَها عبر `flashError` — فتفحص هي كوكي الجلسة وتفتح البوّابة
 * للزائر بدل الرسالة. لا تعديلَ على مكوّنٍ واحدٍ من مكوّنات الأفعال،
 * ولا اعتمادَ على نصِّ الخطأ (رسائلُ Server Actions قد تُقنَّع في
 * الإنتاج — الكوكي أصدقُ منها).
 */

export const LOGIN_GATE_EVENT = "loopz:login-gate";

/**
 * هل للزائر جلسة؟ كوكيز Supabase (`sb-<ref>-auth-token`) تُكتب بلا
 * `HttpOnly` عمداً — عميلُ المتصفّح يحتاج قراءتها — فوجودُها هو
 * الفيصل. وعند أيّ شكٍّ (بيئة بلا `document`) نعدّه مسجّلاً حتى لا
 * نحجب رسالةَ خطأٍ حقيقيّة عن صاحب حساب.
 */
export function hasAuthCookie(): boolean {
  try {
    return document.cookie.split("; ").some((c) => c.startsWith("sb-") && c.includes("-auth-token"));
  } catch {
    return true;
  }
}

/** افتح ورقةَ الدخول — يستقبلها `LoginGateHost` المركَّب في الـlayout */
export function openLoginGate() {
  try {
    window.dispatchEvent(new Event(LOGIN_GATE_EVENT));
  } catch {
    /* لا شيء — الورقة تحسينٌ والخادم يحرس على كلِّ حال */
  }
}

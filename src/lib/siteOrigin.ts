/**
 * 🔴 **أصلُ الدخول يتبع أصلَ الزائر لا متغيّرَ البيئة** (D-623، بلاغُ
 * مشعل من iPhone: «كل ما أطلع من البرنامج يخرجني من الحساب») —
 * **التشخيصُ من قاعدة auth نفسِها**: ثلاثُ جلساتٍ جديدةٍ له في يومٍ
 * واحد (٠٨:٤٥ · ٠٩:٥٢ · ١٣:٢٤) وجلساتُه القديمةُ حيّةٌ تتجدّد في
 * سياقٍ آخر — **أي أن تطبيقَه المثبَّت لا يملك الكوكيز أبداً.**
 *
 * **والآليّة**: تطبيقُه مثبَّتٌ من أيّام `meshahed.vercel.app` (حسابُه
 * من ٧ أغسطس، قبل النطاق الجديد). زرُّ الدخول كان يبني `redirectTo`
 * من `NEXT_PUBLIC_SITE_URL` (= loopztv.com المؤكَّدةُ من الحزمة
 * المنشورة) — **فكوكي مُصادقة PKCE يُكتب على أصلٍ والتبادلُ يجري على
 * أصلٍ آخر، وكوكيز الجلسة تهبط على loopztv.com ولا تصل قشرةَ تطبيقه
 * إطلاقاً** — فكلُّ فتحٍ للأيقونة يفتح أصلاً بلا جلسة: خروجٌ حتميٌّ
 * في كلِّ مرّة.
 *
 * **والعلاج**: الدخولُ يبقى على الأصل الذي يقف عليه الزائرُ **إذا كان
 * أصلاً موثوقاً** — فتُكتب الكوكيز كلُّها حيث يعيش تطبيقُه. **والقائمةُ
 * مغلقةٌ بأسمائها** لا ترويسةً يكتبها العميل (حجّةُ أمنِ التحويل في
 * `auth/callback` باقيةٌ بحرفها): من جاء من أصلٍ غريبٍ يُرَدّ إلى
 * النطاق القانونيّ.
 *
 * **قاعدةٌ واحدةٌ لقارئَيها** (D-145): زرُّ الدخول (`GoogleButton`)
 * ووجهةُ التبادل (`auth/callback`).
 */
export const TRUSTED_ORIGINS = [
  "https://loopztv.com",
  "https://meshahed.vercel.app",
] as const;

/** أصلُ الدخول: أصلُ الزائر إن كان موثوقاً، وإلا النطاقُ القانونيّ */
export function resolveAuthBase(origin: string): string {
  if ((TRUSTED_ORIGINS as readonly string[]).includes(origin)) return origin;
  return process.env.NEXT_PUBLIC_SITE_URL?.replace(/\/$/, "") ?? origin;
}

import "server-only";

/**
 * **هل مزوّدُ X مفعَّلٌ في المشروع الآن؟** (D-839)
 *
 * 🔑 **زرٌّ يَعِد بربطٍ ولا مزوّدَ خلفه أسوأُ من غيابه** (D-217) —
 * **والبديلُ عن هذا الفحص أن يضغط العضوُ فيرى خطأً من GoTrue بلغةٍ
 * لا يفهمها.** **فالصفُّ لا يُرسم حتّى يوجد ما يفتحه.**
 *
 * 🔑 **ولا متغيّرَ بيئةٍ ثانٍ يُضاف ليُنسى**: **GoTrue نفسُها تُسأل** —
 * **فمصدرُ الحقيقة هو المشروع لا رايةٌ نكتبها بيدنا**، **والزرُّ يظهر
 * في اللحظة التي يُفعَّل فيها المزوّد بلا نشرٍ جديد** (وهي قاعدةُ
 * D-570: **الحالةُ تُقاس ولا تُفترض**).
 *
 * 🔴 **والسؤالُ `/authorize` لا `/settings` — وقد جرّبتُ الثانيةَ فكذبت.**
 * **`/auth/v1/settings` تُعيد في هذا الإصدار قائمةَ مزوّدين ثابتةً ليس
 * فيها `x` أصلاً** — آخرُ ما فيها `twitter: false` — **فبقيت تقول
 * «مطفأ» والمزوّدُ مفعَّلٌ في اللوحة ومحفوظ.** 🔑 **ووثيقةٌ تصف حقلاً
 * لا تضمن وجودَه في الإصدار المنشور** — **يُقاس الجوابُ ولا يُفترض
 * شكلُه.**
 *
 * 📏 **و`/authorize` تفرّق قياساً**: **المفعَّلُ يردّ تحويلاً (3xx) إلى
 * صفحة إذنِه، والمطفأُ يردّ `400 validation_failed`** — **مُختبَرٌ على
 * ثلاثة في المشروع نفسِه**: `x` تحويلٌ · `google` تحويلٌ ·
 * `facebook` ٤٠٠.
 * ⚠️ **ولا أثرَ للسؤال**: **بناءُ رابطِ إذنٍ لا يُنشئ جلسةً ولا صفّاً**،
 * **ولا يُتبع التحويلُ أصلاً** (`redirect: "manual"`).
 *
 * ⚠️ **والافتراضُ عند أيِّ فشلٍ «مطفأ»**: شبكةٌ تعثّرت أو شكلٌ تغيّر —
 * **والغيابُ أهونُ من بابٍ يُفتح على خطأ** (D-179: الافتراضُ الآمن
 * أقلُّ سلوكاً).
 *
 * ⚠️ **ومهلةٌ في الذاكرة عشرُ دقائق**: **هذه القيمةُ تتغيّر مرّةً في
 * عمر المشروع** — **ونداءُ شبكةٍ مع كلِّ فتحةِ صفحةِ تعديلٍ ثمنٌ بلا
 * مقابل** (D-470). **وذاكرةُ العمليّة تكفي**: خطأُ قراءةٍ عمرُه عشرُ
 * دقائق بعد التفعيل، **ولا شيءَ يُكسر.**
 */

const TTL_MS = 10 * 60 * 1000;
let cache: { at: number; on: boolean } | null = null;

export async function xLinkEnabled(): Promise<boolean> {
  const now = Date.now();
  if (cache && now - cache.at < TTL_MS) return cache.on;

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !key) return false;

  let on = false;
  try {
    const res = await fetch(`${url}/auth/v1/authorize?provider=x`, {
      headers: { apikey: key },
      /* **ولا يُتبع التحويل**: نريد رمزَ الحالة لا صفحةَ X */
      redirect: "manual",
      /* **لا كاشَ لطبقة Next هنا**: المهلةُ أعلاه هي الكاش،
         **وكاشان لقيمةٍ واحدةٍ يفترقان** (D-145). */
      cache: "no-store",
    });
    /* **التحويلُ «مفعَّل» و٤٠٠ «مطفأ»** — وما سواهما يُقرأ مطفأً */
    on = res.status >= 300 && res.status < 400;
  } catch {
    on = false;
  }

  cache = { at: now, on };
  return on;
}

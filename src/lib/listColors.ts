/**
 * ============ ألوانُ أغلفة القوائم — سجلٌّ واحد (D-824) ============
 *
 * **البندُ الخامسُ من خطّة الـ٢٤**: «أغلفةُ القوائم وألوانُها» —
 * **والغلافُ قائمٌ منذ D-208، والجديدُ اللون.**
 *
 * 🔑 **والقاعدةُ تخزّن رمزاً والشيفرةُ تعرف قيمتَه** (D-145): **قائمةٌ
 * تُوسَّع بلا هجرةٍ ثانية**، **وقيدُ الجدول شكلٌ لا تعداد.**
 *
 * 🔑 **وقائمةٌ مغلقةٌ لا لونٌ حرّ**: **لونٌ يختاره المستخدمُ بلا قيدٍ
 * يعني اسمَ قائمةٍ أبيضَ على أصفرَ فاتحٍ لا يُقرأ** — **والمنعُ في
 * المصدر أرخصُ من حارسٍ في كلِّ سطح** (D-636).
 *
 * 🔑 **ولا حاجةَ إلى لونِ نصٍّ مع كلِّ لون**: **البطاقةُ ترسم اسمَها فوق
 * حجابٍ بلون `--surface` نفسِه** (`ListCardShell`) — **والنصُّ محبوسٌ في
 * عمود الحجاب** (D-686) — **فاللونُ يقع في الجهة البعيدة حيث تقع
 * الملصقاتُ اليوم.** **ولذلك يصحّ في `daylight` كما يصحّ في الداكن بلا
 * قيمتين لكلِّ لون.**
 *
 * ⚖️ **واللونُ يحلُّ محلَّ الغلاف والملصقات لا يجتمع معهما** (D-462):
 * **غلافٌ واحدٌ لا اثنان**، **و`setListCover` تمحو أحدَهما حين تكتب
 * الآخر.**
 */

export interface ListColor {
  /** الرمزُ المخزَّن — `^[a-z]{3,12}$` كقيد الجدول (الهجرة ١٦٢) */
  id: string;
  ar: string;
  en: string;
  /** طرفا التدرّج — **من الفاتح إلى الغامق في اتّجاه القراءة** */
  from: string;
  to: string;
}

/**
 * **ثمانيةٌ لا أكثر** — **وصفٌّ من ستّة عشر مربّعاً يُختار منه بالحظّ**
 * (نفسُ حجّة سقفِ الثيمات). **ومتوسّطةُ الإشباع عمداً**: **الفاقعُ يبتلع
 * الملصقاتِ المجاورةَ في الشبكة**، **والباهتُ يُقرأ عطلاً في الرسم.**
 */
export const LIST_COLORS: ListColor[] = [
  { id: "amber", ar: "كهرمان", en: "Amber", from: "#f59e0b", to: "#b45309" },
  { id: "rose", ar: "وردي", en: "Rose", from: "#fb7185", to: "#9f1239" },
  { id: "crimson", ar: "قرمزي", en: "Crimson", from: "#ef4444", to: "#7f1d1d" },
  { id: "violet", ar: "بنفسجي", en: "Violet", from: "#a78bfa", to: "#5b21b6" },
  { id: "sky", ar: "سماوي", en: "Sky", from: "#38bdf8", to: "#075985" },
  { id: "teal", ar: "فيروزي", en: "Teal", from: "#2dd4bf", to: "#115e59" },
  { id: "lime", ar: "ليموني", en: "Lime", from: "#a3e635", to: "#3f6212" },
  { id: "slate", ar: "رمادي", en: "Slate", from: "#94a3b8", to: "#1e293b" },
];

const BY_ID = new Map(LIST_COLORS.map((c) => [c.id, c]));

/** **رمزٌ لا نعرفه لا لون** — **والفاسدُ يسقط صامتاً** (نمطُ `ui_state`) */
export function listColor(id: string | null | undefined): ListColor | null {
  return id ? (BY_ID.get(id) ?? null) : null;
}

/** **هل هو رمزٌ معتمد؟** — **حارسُ الكتابة في الخادم** */
export function isListColor(id: unknown): id is string {
  return typeof id === "string" && BY_ID.has(id);
}

/**
 * **التدرّجُ جاهزاً للنمط السطريّ.**
 * ⚠️ **و`to bottom left` لا `to right`**: **الاتّجاهُ الأفقيُّ ينقلب مع
 * الاتّجاه** (RTL) **فينقلب معه أيُّ طرفٍ يقع تحت الحجاب** — **والقطريُّ
 * النازلُ يقرأ واحداً في الاتّجاهين.**
 */
export function listColorCss(c: ListColor): string {
  return `linear-gradient(to bottom left, ${c.from}, ${c.to})`;
}

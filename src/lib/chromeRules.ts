/**
 * قواعدُ «كسوة» التطبيق حسب المسار — مصدرٌ واحدٌ للحقيقة.
 *
 * (جولة ١٩ أغسطس ليلاً، طلبُ أحمد: «اجعل التحكم في السلوك مركزيًا بدل
 * توزيع الشروط داخل كل صفحة».)
 *
 * كان قرارُ «هل يعمل السحبُ للتحديث هنا؟» شرطاً داخل `PullToRefresh`
 * وقرارُ «هل تظهر الترويسة؟» شرطاً داخل `HeaderShell` وثالثاً داخل
 * `BottomNav` — **وثلاثةُ أماكن لسؤالٍ واحد تفترق يومَ يُعدَّل أحدُها
 * ويُنسى الباقي.** هذا الملفُّ يجيب وحدَه، والمكوّناتُ تسأل.
 *
 * **ولماذا قوائمُ سماحٍ لا قوائمُ منع (في السحب):** صفحةٌ جديدةٌ تُنشأ
 * غداً يجب أن تُولد بلا سحبٍ للتحديث حتى يُقرَّر لها — **والافتراضُ
 * الآمن هو الأقلُّ سلوكاً.**
 */

/**
 * **السحبُ للتحديث في سطحَين اثنين فقط** (طلبُ أحمد بنصّه: «احصر
 * Pull to Refresh حصريًا في Community وDiscover»):
 *
 * - `/people` — المجتمع: خلاصةٌ اجتماعيّةٌ تتجدّد بفعل الآخرين،
 *   والسحبُ سؤالُ «ماذا استجدّ؟» بمعناه الحرفيّ.
 * - `/news` — اكتشف بتبويباته (مسلسلات/أفلام/أنمي/قوائم): التبويبُ
 *   في الاستعلام لا في المسار، فالمسارُ واحدٌ يغطّيها كلَّها.
 *
 * **وكلُّ ما عداهما بلا سحبٍ** — الرئيسيةُ والمكتبةُ تتجدّدان عند كلِّ
 * تأشيرةٍ وعودةٍ للتبويب، وصفحاتُ التفاصيل ثابتةُ المحتوى، والإعداداتُ
 * نماذجُ لا خلاصات.
 */
export function allowsPullToRefresh(pathname: string): boolean {
  return pathname === "/people" || pathname === "/news";
}

/**
 * **الترويسةُ والشريطُ السفليُّ يختبئان مع النزول ويعودان مع الرجوع** —
 * إلا حيث يكون الثباتُ هو الصواب:
 *
 * - **الإعداداتُ وكلُّ فروعها**: رحلةٌ لها بدايةٌ ونهاية، وترويستُها
 *   تحمل زرَّ الرجوع — **وإخفاءُ باب الخروج عن ساحبٍ يقرأ نموذجاً
 *   طويلاً حبسٌ لا ترتيب.**
 * - `/login` و`/welcome`: شاشتان قصيرتان مركّزتان بلا كسوةٍ أصلاً.
 *
 * **والفروعُ تدخل تلقائيّاً** (`startsWith`) — مسارُ إعداداتٍ يُنشأ
 * غداً يرث الاستثناءَ بلا سطرٍ جديد.
 */
export function allowsAutoHideChrome(pathname: string): boolean {
  return !(
    pathname === "/profile/edit" ||
    pathname === "/login" ||
    pathname === "/welcome" ||
    pathname.startsWith("/profile/settings")
  );
}

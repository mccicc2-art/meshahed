/**
 * A-77 (المدقّق ٢٣ نوفمبر ٢٠٢٦) — مهلةٌ افتراضيّة لنداءات القاعدة من الخادم.
 *
 * **لماذا**: عميلُ Supabase في الخادم لا يضع مهلةً لنداءاته، فحين تتعطّل القاعدة يبقى الطلبُ منتظراً حتى يقطعه
 * Vercel عند ٣٠٠ ثانية — والعضو أمام شاشةٍ معلّقة خمسَ دقائق بدل خطأٍ سريع (حادثة ٢٢ نوفمبر: ٧٢ مهلة).
 *
 * 🔑 **لماذا ١٥ ثانية لا تقطع نداءً سليماً**: القاعدةُ نفسُها تقطع استعلامَ العضو عند ٨ث والضيف عند ٣ث
 * (`statement_timeout` لدوريهما)، ورفعُ الصور ≤ ٤ م.ب من خادمٍ إلى خادم — فما تجاوز ١٥ث عالقٌ لا بطيء.
 * عميلُ الخدمة (`service.ts`) لا يُلفّ: دفعاتُ الإدارة والمهامّ المجدولة قد تطول عن قصد.
 *
 * ⚖️ **نداءٌ يحمل إشارتَه يُترك كما هو** — صاحبُه أعلمُ بمهلته.
 */
export const DB_TIMEOUT_MS = 15_000;

export function withDefaultTimeout(base: typeof fetch, ms: number = DB_TIMEOUT_MS): typeof fetch {
  return (input, init) => {
    if (init?.signal) return base(input, init);
    return base(input, { ...init, signal: AbortSignal.timeout(ms) });
  };
}

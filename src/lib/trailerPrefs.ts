/**
 * 🆕 **آخرُ اختيارٍ للصوت** (D-726، شرطُ أحمد: «صامتٌ افتراضيّاً أوّل
 * مرّة، ثمّ يُحفظ آخر اختيار للمستخدم»).
 *
 * 🔑 **وكوكيزٌ لا `localStorage`** — **وصفةُ `tabPrefs` و`myRows` حرفاً**
 * (القاعدة ٦): **الصفحةُ خادميّةٌ فتقرأ التفضيلَ قبل الرسم** — **ولو
 * سكن المتصفّحَ وحدَه لبدأ كلُّ مشغّلٍ صامتاً ثمّ قفز إلى الصوت بعد
 * الترطيب**، **وقفزةُ صوتٍ أسوأُ من صمتٍ ثابت.** **وتعمل للزائر بلا
 * حساب.**
 */
export const TRAILER_SOUND_COOKIE = "loopz_trailer_sound";

/** ⚖️ 🆕 **والافتراضُ صار الصوتَ** (D-771 بحكمه: «دائماً الصوت شغال
    والي مزعجه يحط صامت» — نقضٌ صريحٌ منه لشرطه في D-726 «صامتٌ
    افتراضيّاً أوّل مرّة»). آخرُ اختيارٍ يبقى محفوظاً: من كتم مرّةً
    (`off`) يبقى مكتوماً حتى يفكّه بيده — فلا يُفرَض صوتٌ على من رفضه.
    والمتصفّحُ يبقى الحَكَم: حيث يمنع WebKit الصوتَ الآليَّ يعمل المقطعُ
    صامتاً ولا يقف (D-771: «دائماً شغّال» مقدَّمةٌ على الصوت). */
export function parseTrailerSound(raw: string | undefined | null): boolean {
  return raw !== "off";
}

export function serializeTrailerSound(on: boolean): string {
  return on ? "on" : "off";
}

/**
 * 🔴 🆕 **ويُكتب من المتصفّح لا من الخادم** (D-747، بلاغُ أحمد: «يحدّث
 * الصفحة إذا ضغطت على السماعة»).
 *
 * 🔑 **وكلُّ فعلٍ خادميٍّ يُعيد رسمَ الصفحة، لا الذي يُبطل التخبئة
 * وحدَه**: **ردُّ الفعل الخادميّ يحمل شجرةَ الخادم من جديد** — **فتبديلُ
 * كوكي كان يكلّف رحلةً ورسماً كاملاً لصفحةٍ لم يتغيّر فيها شيءٌ من
 * الخادم.**
 * 🔑 **والقاعدة: ما كان تفضيلاً للجهاز يُكتب في الجهاز** — **ولا يُستدعى
 * الخادمُ ليكتب ما لا يقرؤه إلّا في أوّل رسم.**
 * ⚠️ **والقراءةُ تبقى خادميّةً كما هي** (رأسُ الملفّ): **الكوكي هو
 * الجسرُ، والفرقُ في من يمسك القلم.**
 * ⚠️ **و`SameSite=Lax` و`Max-Age` كما كتبها الفعلُ حرفاً** — **ورقمان
 * مختلفان لكوكي واحدٍ يعني تفضيلاً يموت في متصفّحٍ ويعيش في آخر.**
 */
export function writeTrailerSound(on: boolean): void {
  try {
    document.cookie =
      `${TRAILER_SOUND_COOKIE}=${serializeTrailerSound(on)}` +
      `; path=/; max-age=${60 * 60 * 24 * 365}; samesite=lax`;
  } catch {
    /* متصفّحٌ يمنع الكوكيز — الصوتُ يعمل هذه الجلسة ولا يُحفظ */
  }
}

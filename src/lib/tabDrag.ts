/**
 * **قناةُ السحب — رقمٌ واحدٌ بين الجسم والرأس** (D-276).
 *
 * `TabPager` يحرّك اللوحات، **و`TabUnderline` يحرّك الشريط تحت الاسم**،
 * وهما مكوّنان متباعدان في الشجرة (أحدهما داخل الرأس اللاصق والآخر تحته).
 *
 * **ولا حالةَ React بينهما**: الرقمُ يتغيّر في كل إطارِ حركةٍ للإصبع،
 * **وإعادةُ رسم الرأس ستّين مرّةً في الثانية ثمنٌ بلا مقابل** — والحركةُ
 * تُكتب على `style` مباشرةً. **وهي قاعدةُ D-246 حرفاً**: ما لا يقرؤه
 * React لا يمرّ به.
 *
 * **والمعنى:** `0` ساكن · **موجبٌ يعني «ذاهبٌ إلى التبويب التالي»** ·
 * وسالبٌ إلى السابق · و`±1` وصلَ. **والتاليُ ترتيبيٌّ لا جغرافيّ** —
 * فالعربيّةُ لا تقلب الإشارة هنا، يقلبها `TabPager` قبل النشر (D-216).
 */
let progress = 0;
const subs = new Set<(p: number) => void>();

export function setTabDrag(p: number) {
  progress = p;
  for (const f of subs) f(p);
}

/** يُنادى فوراً بالقيمة الحالية ثم عند كل تغيير — ويعيد دالّةَ الفصل */
export function onTabDrag(f: (p: number) => void) {
  subs.add(f);
  f(progress);
  return () => {
    subs.delete(f);
  };
}

/**
 * **قناةُ الإيماءات — رقمٌ واحد، ومالكٌ واحد** (D-276 · D-277).
 *
 * ================= ١ · الرقم =================
 *
 * `TabPager` يحرّك اللوحات، **و`TabUnderline` يحرّك الشريط تحت الاسم**،
 * وهما مكوّنان متباعدان في الشجرة. **ولا حالةَ React بينهما**: الرقمُ
 * يتغيّر في كل إطارِ حركةٍ للإصبع، **وإعادةُ رسم الرأس ستّين مرّةً في
 * الثانية ثمنٌ بلا مقابل** (D-246).
 *
 * **والمعنى:** `0` ساكن · **موجبٌ «ذاهبٌ إلى التبويب التالي»** · وسالبٌ
 * إلى السابق · و`±1` وصلَ. **والتاليُ ترتيبيٌّ لا جغرافيّ.**
 *
 * ================= ٢ · والمالك — وهذا عطلٌ رآه أحمد =================
 *
 * **بلاغُه بلقطة: «أقدر ألفّ يمين أو يسار وأسحب تحت في نفس الوقت»** —
 * وفي اللقطة لوحتان مزاحتان أفقيّاً **ومؤشّرُ التحديث دائرٌ فوقهما**.
 * **ثلاثُ إيماءاتٍ تتنازع إصبعاً واحداً**: انزلاقُ اللوحات، وتمريرُ
 * المستند، والسحبُ للتحديث.
 *
 * **والسببُ أن كلَّ واحدةٍ كانت تقرأ اللمسَ وحدَها ولا تعرف بالأخرى** —
 * ثلاثةُ مستمعين على `document` و`window` لا حَكَمَ بينهم.
 *
 * **فالحَكَمُ هنا: مالكٌ واحدٌ للّمسة، يُطلَب مرّةً ويُردّ عند رفع
 * الإصبع.** **ومن سبق مَلَك** — ومن جاء بعده يقف ساكناً لا يتزاحم.
 * **والقسمةُ عادلةٌ بمعناها لا بالتساوي**: الأفقيُّ يملك السحبَ الأفقيّ،
 * والرأسيُّ يملك التمريرَ والتحديث. **وإيماءتان في وقتٍ واحدٍ ليستا
 * ميزةً، هما لخبطة** (نصُّ أحمد).
 */
let progress = 0;
const subs = new Set<(p: number) => void>();

export function setTabDrag(p: number) {
  progress = p;
  for (const f of subs) f(p);
}

/** يُنادى فوراً بالقيمة الحالية ثم عند كل تغيير — ويعيد دالّةَ الفصل */
export function onTabDrag(f: (p: number) => void) {
  subs.add(f);
  f(progress);
  return () => {
    subs.delete(f);
  };
}

/* ============================================================
   الحَكَم — مالكٌ واحدٌ للّمسة الواحدة
   ============================================================ */

type Axis = "x" | "y";
let owner: Axis | null = null;

/**
 * **يطلب ملكيّةَ اللمسة.** يعود `true` إن مُنحت (أو كانت له أصلاً)،
 * و`false` إن كانت بيد غيره — **فيقف طالبُها ولا يتزاحم.**
 */
export function claimGesture(axis: Axis): boolean {
  if (owner === null) owner = axis;
  return owner === axis;
}

/** **هل يملكها غيري؟** — يُسأل قبل كل حركة، لا عند البداية وحدها */
export function gestureTakenBy(axis: Axis): boolean {
  return owner !== null && owner !== axis;
}

/**
 * **تُردّ عند رفع الإصبع** — ولا يردّها إلا مالكُها.
 * **ومن ردّ ما لا يملك أعاد الفوضى**: مستمعٌ ينتهي قبل أخيه كان
 * سيفتح البابَ لِما بعده في اللمسة نفسِها.
 */
export function releaseGesture(axis: Axis) {
  if (owner === axis) owner = null;
}

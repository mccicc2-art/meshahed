/** متوسّطُ الحلقة حين لا تُخزَّن مدّتُها — **الرقمُ الأقدم، وهو المرجع** */
export const EPISODE_FALLBACK_MIN = 40;

/** متوسّطُ الفيلم حين لا تُخزَّن مدّتُه */
export const MOVIE_FALLBACK_MIN = 110;

export function runtimeMinutes(
  kind: "episode" | "movie",
  runtime: number | null | undefined,
): number {
  if (typeof runtime === "number" && runtime > 0) return runtime;
  return kind === "movie" ? MOVIE_FALLBACK_MIN : EPISODE_FALLBACK_MIN;
}

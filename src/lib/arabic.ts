/**
 * **تطبيعُ العربية للبحث المحلّي** (D-350، مراجعةُ المكتبة بند ٤).
 *
 * ================= العطل الذي يوجد هذا الملفّ لأجله =================
 *
 * `title.toLowerCase().includes(needle)` **لا يعرف العربية**: من كتب
 * «الاب» لا يجد «الأب»، ومن كتب «قصه» لا يجد «قصّة»، ومن كتب «يحيي» لا
 * يجد «يحيى». **ولا مُطبِّعَ عربيّاً في المستودع كلِّه** — وواجهةٌ
 * عربيّةٌ أوّلاً (القاعدة ١٧) لا يعرف بحثُها لغتَها **عطلٌ لا نقصُ
 * ميزة.**
 *
 * ================= وأربعُ عمليّاتٍ لا أكثر =================
 *
 * **لا مكتبةَ ولا `Intl.Collator`**: القائمةُ في الذاكرة والحرفُ الواحدُ
 * يصفّي فوراً (D-006)، **وكلُّ ما نحتاجه أن يتطابق ما يكتبه الإصبعُ مع
 * ما يراه**. فأربعُ خطوات:
 *  ١) **إسقاطُ التشكيل والتطويل** (`ـ` والحركاتُ ٠٦٤B–٠٦٥F) — يُكتبان في
 *     العناوين ولا يُكتبان في البحث.
 *  ٢) **توحيدُ الألف** (أ إ آ ٱ → ا) — **أكثرُ خطأٍ إملائيٍّ شيوعاً**،
 *     وليس خطأً أصلاً في الاستعمال اليومي.
 *  ٣) **الياءُ والتاءُ المربوطة** (ى → ي · ة → ه) — «قصه/قصة»
 *     و«يحيي/يحيى».
 *  ٤) **الأرقامُ الهنديّة إلى العربية** (٠١٢… → 012…) — «الجزء ٢» و
 *     «الجزء 2» عملٌ واحد.
 *
 * ⚠️ **ولا تُغيَّر النصوصُ المعروضة أبداً** — هذا مفتاحُ مقارنةٍ يُبنى
 * ويُرمى، **والعنوانُ يبقى كما كتبه أهلُه** (D-048).
 *
 * ⚠️ **ويعمل على اللاتينيّة بلا أثرٍ ضارّ** (`toLowerCase` وحدَها تمسّها)
 * — فمصدرٌ واحدٌ للبحث في تبويبٍ فيه العربيُّ والإنجليزيُّ معاً.
 */
const ARABIC_MARKS = /[ً-ٰٟـ]/g;

export function normalizeSearch(input: string): string {
  return input
    .toLowerCase()
    .replace(ARABIC_MARKS, "")
    .replace(/[آأإٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    /* الأرقامُ الهنديّة (٠٦٦٠–٠٦٦٩) والفارسيّة (٠۶F٠–٠۶F٩) */
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x06f0))
    .trim();
}

/**
 * **ترتيبُ الأسماء بلغة الواجهة لا بلغة الجهاز** (D-350).
 *
 * `a.localeCompare(b)` بلا وسيطٍ يتبع لغةَ المتصفّح — **فترتيبُ مكتبتك
 * يتغيّر بتغيّر إعداداتِ جهازك لا إعداداتِ حسابك**، وهو ما تمنعه القاعدة
 * ١٧ (العربيّةُ أوّلاً بحكم المنتَج لا بحكم الجهاز).
 */
export function byTitle(locale: "ar" | "en") {
  const cmp = new Intl.Collator(locale, { numeric: true, sensitivity: "base" });
  return (a: string, b: string) => cmp.compare(a, b);
}

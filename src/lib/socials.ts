/**
 * **حسابُ X في الملفّ الشخصيّ** (D-546 → ⚖️ 🔴 D-839).
 *
 * ================= ملفٌّ نقيٌّ لا يعرف قاعدةً ولا شبكة =================
 *
 * **سجلٌّ ودالّتان**: ما المنصّة، وكيف يُنقّى المعرّف، وكيف يُبنى
 * الرابط. **يقرؤه نموذجُ التحرير (عميل) وصفحةُ الملفّ (خادم) معاً**
 * (D-193)، **ويُختبر بلا متصفّح.**
 *
 * ================= ويُخزَّن المعرّفُ لا الرابط =================
 *
 * **«imeshal» لا «https://x.com/imeshal»** — لسببين:
 *  ١) **الرابطُ يُبنى عند العرض**، فيومَ صار «تويتر» اسمُه «X» لم
 *     تُعَد كتابةُ صفوف الناس.
 *  ٢) **ونصٌّ يكتبه المستخدمُ ويُوضع في `href` كما هو بابُ حقن**
 *     (`javascript:`): **المعرّفُ يمرّ بمصفاةِ حروفٍ ضيّقة**، **ولا
 *     يُبنى الرابطُ إلّا من نطاقٍ نكتبه نحن.** **وهذا هو الحارس، لا
 *     `rel="noopener"` وحدَه.**
 *
 * ⚠️ **والمصفاةُ باقيةٌ وإن صار المعرّفُ يأتي من المزوّد لا من اليد**
 * (D-839): **بياناتُ مزوّدٍ خارجيٍّ مُدخَلٌ لا ثقة** — **ولا يُبنى
 * رابطٌ من نصٍّ لم يمرّ بها، جاء من حيث جاء.**
 *
 * ================= 🔴 ولماذا سقطت الثلاثةُ الأخرى (D-839) =================
 *
 * **حكمُ أحمد**: «أبغاه ربط حقيقي مو بس كتابة اسم، بحيث يعمل تسجيل
 * دخول عن طريقهم عشان يكون أكثر مصداقيّة» — **ثمّ حكمه بعد البحث**:
 * «تسقط الثلاثة من الملفّ».
 *
 * **والسببُ أنّ ثلاثتَها لا تستطيع أن تعطيَنا المعرّف، لا أنّنا لم
 * نبنِ** — **وهذا فرقٌ يُكتب كي لا يُعاد البحثُ بعد سنة:**
 *  - **سناب شات**: `Login Kit` يعطي **الاسمَ الظاهرَ وBitmoji ومعرّفاً
 *    خاصّاً بتطبيقنا** — **ولا يعطي اسمَ المستخدم أبداً** (النطاقاتُ
 *    الأربعةُ المعلنةُ ليس فيها اسمُ مستخدم). **فالتوثيقُ يثبت أنّ له
 *    حساباً ولا يثبت أيَّ حساب** — **وشارةٌ كهذه كذبةٌ مهذّبة.**
 *  - **إنستقرام**: `Basic Display API` **أُغلق في ٤ ديسمبر ٢٠٢٤**،
 *    **وبديلاه لا يقبلان إلّا حسابات Business/Creator** — **والحسابُ
 *    الشخصيُّ لا يستطيع تسجيلَ الدخول أصلاً.**
 *  - **فيسبوك**: الدخولُ يعمل، **لكنّ `username` مهجورٌ منذ Graph
 *    v2.0** — **فتحصل على معرّفٍ داخليٍّ لا على رابطِ ملفّ**، **ولا
 *    شيءَ يُضغط.**
 *
 * 🔑 **والقاعدةُ المستخلَصة**: **ميزةٌ تعتمد على منصّةٍ أخرى تُفحص
 * قدرتُها قبل أن يُرسم حقلُها** — **وأربعةُ حقولٍ رُسمت في D-546 وثلاثةٌ
 * منها لم تكن لتصل إلى شيءٍ يوماً.**
 */

/** **منصّةٌ واحدة** — والثلاثةُ الأخرى سقطت بحكمه بعد البحث (أعلاه) */
export type SocialKey = "x";

export interface SocialSpec {
  key: SocialKey;
  /** اسمُ المنصّة كما تكتبه هي — **لا يُترجَم**: «X» علامةٌ لا كلمة */
  label: string;
  /** أصلُ الرابط — **نكتبه نحن، ولا يأتي من المستخدم أبداً** */
  base: string;
  /** الحروفُ المسموحة في المعرّف عند تلك المنصّة */
  pattern: RegExp;
  max: number;
  /**
   * 🗑️ **مثالٌ في الحقل الفارغ — ويسقط مع الحقل في الالتزام التالي**
   * (D-028): **النموذجُ الذي يقرؤه ما زال هو القديم في هذه اللحظة**،
   * **وحقلٌ يُحذف قبل قارئه يكسر البناء.**
   */
  placeholder?: string;
}

export const SOCIALS: readonly SocialSpec[] = [
  {
    key: "x",
    label: "X",
    base: "https://x.com/",
    pattern: /^[A-Za-z0-9_]{1,15}$/,
    max: 15,
    placeholder: "imeshal",
  },
] as const;

const BY_KEY = new Map<SocialKey, SocialSpec>(SOCIALS.map((s) => [s.key, s]));

export type Socials = Partial<Record<SocialKey, string>>;

/**
 * **تنقيةُ معرّفٍ واحد** — يقبل «@name» و«name» ورابطاً ملصوقاً،
 * **ويأخذ آخرَ مقطعٍ في مساره**، وتُرمى المعاملات.
 *
 * **ويعيد `null` لما لا يطابق المصفاة** — **ولا يُخزَّن نصٌّ لا يصلح
 * رابطاً** (D-063: الغائبُ أصدقُ من الكاذب).
 */
export function cleanHandle(key: SocialKey, raw: string): string | null {
  const spec = BY_KEY.get(key);
  if (!spec) return null;

  let v = String(raw ?? "").trim();
  if (!v) return null;

  /* **رابطٌ ملصوق؟ خُذ آخرَ مقطعٍ ذي معنًى** — وتسقط `?` و`#` معه */
  if (/^https?:\/\//i.test(v) || v.includes("/")) {
    v = v.split(/[?#]/)[0]!;
    const parts = v.split("/").filter(Boolean);
    v = parts[parts.length - 1] ?? "";
  }

  v = v.replace(/^@+/, "").trim();
  if (!v) return null;
  if (v.length > spec.max) return null;
  return spec.pattern.test(v) ? v : null;
}

/**
 * **تنقيةُ السجلّ كلِّه** — **المفتاحُ المجهولُ يسقط والقيمةُ الفاسدة
 * تسقط**، **والحقلُ الفارغ يعني الحذف** (فمن مسح حسابَه مسحه).
 *
 * **يقرؤها الكاتبُ والقارئُ معاً** (ثلاثيّةُ D-177): **عمودُ `jsonb`
 * بلا قيدِ مفاتيحَ في القاعدة، فالحارسُ هنا مرّتين.**
 *
 * 🔑 **وهي التي أسقطت الثلاثةَ بلا هجرةِ بيانات** (D-839): **تدور على
 * `SOCIALS` لا على مفاتيح الصفّ** — **فما خرج من السجلّ خرج من القراءة
 * والكتابة معاً في اللحظة نفسِها**، **والقيمُ القديمةُ تبقى في العمود
 * خاملةً لا تُقرأ ولا تُعرض.** ⚠️ **وقد قِيس قبل الحذف**: **صفرُ حسابٍ
 * كتب سنابَ أو إنستقرامَ أو فيسبوك** (٣٢ عضواً) — **فلا بيانَ ضاع.**
 */
export function sanitizeSocials(raw: unknown): Socials {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return {};
  const src = raw as Record<string, unknown>;
  const out: Socials = {};
  for (const spec of SOCIALS) {
    const v = src[spec.key];
    if (typeof v !== "string") continue;
    const clean = cleanHandle(spec.key, v);
    if (clean) out[spec.key] = clean;
  }
  return out;
}

/**
 * **الرابطُ يُبنى من نطاقٍ نكتبه نحن ومعرّفٍ مرّ بالمصفاة** —
 * **ولا يُبنى من نصِّ المستخدم أبداً.** `null` تعني «لا رابط».
 */
export function socialUrl(key: SocialKey, handle: string | null | undefined): string | null {
  const spec = BY_KEY.get(key);
  if (!spec || !handle) return null;
  const clean = cleanHandle(key, handle);
  return clean ? spec.base + encodeURIComponent(clean) : null;
}

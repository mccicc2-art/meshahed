-- (`ahmed` و`khld`)، ٣٥١٠ صفّاً، ٣٢٨ كيلوبايت.
--
-- **مقيسٌ على الإنتاج ٤ سبتمبر ٢٠٢٦:**
--   • صفر سياسة و RLS مفعّلة  → صفر قراءةٍ عبر Data API لأيِّ دور.
--   • صفر عرضٍ يعتمد عليه، صفر `.from()` في الشيفرة — **يتيمٌ تماماً.**
--   • الإصلاحُ نفسُه صحيح: صفر موسمٍ لا يزال ترقيمُه نسبيّاً (`lo < 62`).

-- ⚖️ **ولمَ لا يُحذف الجدولُ في سطرٍ واحدٍ وينتهي الأمر؟**
-- لأنّ العيبَ الذي رفعه التدقيق ليس «وجودَ نسخة» بل **`P6-02`: الجدولُ
-- بلا مفتاحٍ أجنبيٍّ على `user_id`، فصفوفُه تنجو من حذف الحساب** —
-- **عيبٌ في حقِّ المحو.** وهذا العيبُ يُغلق بخطوةٍ آمنةٍ فوراً (القسم ١)،
-- **بينما إسقاطُ الجدول محوٌ لا رجعةَ فيه لبياناتِ عضوَين** ويبقى لأحمد.
--
--   ▸ القسم ١ — ✅ **شُغّل وتحقّق ٤ سبتمبر ٢٠٢٦** (`confdeltype = c` ·
--     الفهرسُ قائم · **٣٥١٠ صفّاً لم تُمَسّ**؛ وقُيس قبله صفر صفٍّ يتيم): مفتاحٌ أجنبيٌّ بحذفٍ متتالٍ. **يُغلق `P6-02`
--     كاملاً**: من يحذف حسابَه اليومَ تختفي صفوفُه من اللقطة معه.
--   ▸ القسم ٢ — **يُشغَّل حين يقرّر أحمد**: إسقاطُ الجدول. **يُغلق `0005`.**
--     الشرطُ الوحيد: القبولُ بأنّ ١١٦٢ صفّاً من سجلِّ مشاهدةِ `khld`
--     المحذوفةِ يومَ الإصلاح لا تعود.
--
-- **وتوصيتي:** شغّل القسم ١ اليوم، وأجّل القسم ٢ إلى ما بعد الإطلاق.
-- ٣٢٨ كيلوبايت لا تشتري شيئاً بحذفها، **وشبكةُ أمانٍ لإصلاحِ بياناتٍ

-- D-1505 — **مصدرُ المشاهدة: من سجّل هذا الصفّ؟** (سجلُّ المشاهدة، المرحلة ٢)
-- ═══════════════════════════════════════════════════════════════════════
--
-- سجلُّ المشاهدة يكتب شارةً بجوار ما لم يسجّله صاحبُه بيده — «Stremio»
-- (جوابُ إشارة Stremio)، «الودجت»، ولاحقاً «تلقائي» (ربطُ المنصّات) و«استيراد».
-- **`null` = بيده**، فلا تعبئةَ لما مضى: كلُّ صفٍّ قديمٍ يبقى بلا شارة.
--
-- **التطبيقُ والخادمُ يعملان قبل هذا الملفّ وبعده** (`src/lib/watchSource.ts`):
-- الوسمُ كتابةٌ ثانيةٌ بعد الإدراج يُبتلع فشلُها، والقراءةُ تعيد الطلبَ بلا
-- العمود إن لم يوجد. فلا ترتيبَ بين رفع الشيفرة وتشغيل هذا.
--
-- لا فهرس: العمودُ يُقرأ مع الصفّ ولا يُسأل به. ولا سياسةَ جديدة: «own watched
-- episodes / movies» (ALL) تغطّي التحديث.
-- يُشغَّل مرّةً في Supabase → SQL Editor (DDL الإنتاج لأحمد).

alter table public.watched_episodes
  add column if not exists source text
  check (source in ('stremio', 'widget', 'import', 'auto'));

alter table public.watched_movies
  add column if not exists source text
  check (source in ('stremio', 'widget', 'import', 'auto'));

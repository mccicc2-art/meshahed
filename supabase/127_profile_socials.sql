-- **طلبُ أحمد: «ضِف في الإعدادات تحت كتابة النِّك نيم أماكنَ مخصّصةً
-- لكتابة حساب تويتر وسناب شات وإنستقرام وفيسبوك».**
--
-- **ولماذا `jsonb` لا أربعةُ أعمدة:** **العددُ ليس أربعةً بطبيعته** —
-- تيك توك ويوتيوب وليتربوكسد أسئلةٌ تُطرح غداً، **وكلُّ واحدةٍ منها
-- هجرةٌ جديدةٌ لو كانت عموداً.** **والقراءةُ واحدةٌ في الحالين** (الصفُّ
-- يُقرأ كاملاً أصلاً)، **فالثمنُ صفر والمرونةُ مكسب.** **وهو نفسُ ما
-- فعله `home_prefs` و`profile_prefs`** — **عائلةٌ قائمةٌ لا نمطٌ جديد.**
--
-- **ويُخزَّن المعرّفُ لا الرابط**: «imeshal» لا «https://x.com/imeshal».
-- **الرابطُ يُبنى عند العرض** — **فمن غيّر النطاقُ اسمَه (تويتر → X)
-- لا يُعاد كتابةُ صفوف الناس.**
--
-- ⚠️ **ولا قيدَ على المفاتيح هنا**: **التنقيةُ في الكاتب**
-- (`sanitizeSocials`) **وفي القارئ** — **وقيدٌ في القاعدة على مفاتيحَ
-- تتغيّر بإضافةِ منصّةٍ يعني هجرةً لكلِّ منصّة**، وهو ما يهرب منه
-- `jsonb` أصلاً. **والحارسُ الحقيقيُّ أن العمودَ لا يُعرض خاماً:**
-- ما لا يعرفه السجلُّ لا يُرسم.
--
-- ⚠️ **وRLS قائمٌ كما هو**: سياسةُ `profiles` واحدةٌ `ALL` بـ`using`
-- و`with check` على `auth.uid() = id` — **صاحبُ الصفّ وحدَه يكتب.**
--
-- rollback: alter table public.profiles drop column if exists socials;
-- ============================================================

alter table public.profiles
  add column if not exists socials jsonb not null default '{}'::jsonb;

-- **كائنٌ لا مصفوفةٌ ولا نصّ** — أرخصُ حارسٍ ممكن، ولا يقيّد المفاتيح
alter table public.profiles
  drop constraint if exists profiles_socials_is_object;
alter table public.profiles
  add constraint profiles_socials_is_object
  check (jsonb_typeof(socials) = 'object');

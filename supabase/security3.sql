-- ============================================================
--  ما كان مكشوفاً
--
--  ثلاث سياسات `select ... using (true)` لدور `authenticated` على
--  `follows` و`watched_episodes` و`watched_movies`. أي شخصٍ مسجَّل دخوله —
--  بالمفتاح العامّ الذي يصل كل متصفّح — كان يستطيع أن يقرأ عبر PostgREST
--  **مكتبة كل مستخدم وسجلّ مشاهدته حلقةً حلقة بأوقاتها**. لا ثغرة تقنية:
--  السياسة كانت تسمح.
--
--  وهذا يناقض D-012 نصّاً («القراءة المباشرة مغلقة كي لا يُعدّد أحدٌ سجلّ
--  غيره») ويناقض «الخصوصية افتراضاً» في وثيقة الرؤية. والفحص الصحّي في
--  `04_Current_Status.md` كُتب ليمسك هذا بعينه — لكنه لم يكن يُشغَّل، فبقي
--  وعداً على ورق. اكتُشف يوم ٨ أغسطس ٢٠٢٦ عند أوّل تشغيلٍ فعليّ له.
--
--  ولماذا الحذف آمن — تُحقّق منه قبل التنفيذ لا بعده:
--   1. لكل جدولٍ من الثلاثة سياسةٌ ثانية `own …` بـ`auth.uid() = user_id`
--      من نوع ALL، فقراءة المستخدم لصفوفه هو لا تتأثّر إطلاقاً.
--   2. بيانات مستخدمٍ آخر تُقرأ في التطبيق عبر دوال definer وحدها:
--      `user_public_follows` و`user_watch_overview` و`user_watched_movie_ids`
--      (security2.sql) — وهي تتجاوز RLS بحكم تعريفها.
--   3. فُحص الكود: أربعٌ وأربعون قراءةً مباشرة لهذه الجداول، كلها مقيّدة
--      بـ`user.id` الحاليّ، ولا واحدة تمرّر معرّف شخصٍ آخر.
--
--  والتراجع — إن ظهر ما لم يُحسب — سطرٌ واحد لكل جدول:
--    create policy "read all follows" on public.follows
--      for select to authenticated using (true);
-- ============================================================

drop policy if exists "read all follows"          on public.follows;
drop policy if exists "read all watched episodes" on public.watched_episodes;
drop policy if exists "read all watched movies"   on public.watched_movies;


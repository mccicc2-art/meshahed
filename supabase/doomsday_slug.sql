--  بالإنجلش، **حتى الوصف بالداخل** المفروض يماثل لغة الحساب».
--
--  ================= السببُ عمودٌ فارغ =================
--
--  **بوّابةُ D-328 تترجم من عرفت هويّته**: `curatedName` تقرأ
--  `source_slug` وتردّ الاسمَ من القاموس. **وقائمةُ الهجرة ١٠١ كُتبت
--  بيدٍ لا بمولِّد** (D-317) **فوُلدت بلا `source_slug`** — **فمرّت
--  بنصّها المخزَّن، وهو عربيّ.** والعطلُ ليس في البوّابة، **العطلُ أن
--  الصفَّ لا يحمل ما تسأل عنه.**
--
--  **والقاموسُ الذي يعطيه معنًى `EDITORIAL` في `universes.ts`** — قاموسُ
--  **أسماءٍ لا قاموسُ بناء**: **`allCuratedSets()` تولِّد قوائم، وصفٌّ
--  بلا مولِّدٍ يدخلها يصير بطاقةً تَعِد بقائمةٍ لا تُبنى** (D-217).
--
--  ================= ⚠️ وهذا `update` على صفٍّ قائم =================
--
--  🔴 **وهو خارجُ الإذن الدائم بنصّه** («لا حذفٌ ولا `drop` ولا تعديلُ
--  بياناتٍ قائمة بهذا الإذن») — **ويُنفَّذ بإذنِ «ممتاز نفّذ الكل»
--  وحدَه**، **ولا يُعمَّم على ما بعده.**
--
--  **وحدودُه معلنةٌ قبل تشغيله**: **صفٌّ واحدٌ بمعرّفه الثابت** ·
--  **عمودٌ واحدٌ** · **وشرطُ `source_slug is null` يجعله لا يكتب فوق
--  هويّةٍ قائمة** — **فإعادةُ تشغيله لا تفعل شيئاً، وتشغيلُه على قاعدةٍ
--  صُحِّحت يدوياً لا يفسدها.** **ولا اسمَ ولا وصفَ ولا عنصرَ يُمَسّ:**
--  **النصُّ المخزَّن يبقى كما هو** (D-328: يُترجَم عند العرض ولا
--  يُستبدل في القاعدة).
-- ═══════════════════════════════════════════════════════════════════════

begin;

update public.user_lists
   set source_slug = 'doomsday-road'
 where id = 'a0d00000-0000-4000-8000-000000000101'
   and source_slug is null;

commit;


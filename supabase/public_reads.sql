begin;

/* **قراءةُ آراء العمل** — تحترم الحساب الخاصّ وإخفاءَ الاسم والمبلَّغَ عنه */
grant execute on function public.title_reviews(integer, text) to anon;

/* **ردودُ الخيط** — نفسُ العمل، وهي التي تجعل الصفحة حواراً لا قائمة */
grant execute on function public.title_replies(integer, text) to anon;

/* **أعدادُ الإعجاب** — الرقمُ وحده؛ و«أعجبتُ به أنا» تعود خطأً بلا هويّة */
grant execute on function public.title_review_likes(integer, text) to anon;

/* **متوسّطُ التقييم وعددُه** — مقامُ النجمة في الترويسة (D-216) */
grant execute on function public.community_rating(integer, text) to anon;


-- =====================================================================
-- 223 — احتفاظُ `runtime_errors`: تسعون يوماً (A-11 · المدقّق ٢١ أكتوبر)
-- =====================================================================
-- أحمد ٢٣ أكتوبر ٢٠٢٦: «2 أ» (تسعون يوماً).
--
-- الجدولُ يكتب نحو خمسمئة صفٍّ في اليوم (أعطالُ الخادم، بلاغاتُ التطبيق، قياساتُ الأداء) ولا يُحذف منه شيء —
-- والاحتفاظُ بلا سببٍ التزامٌ لا أصل (توصيةُ «retention» في صحّة اللوحة). تسعون يوماً تكفي لمقارنة الأداء
-- أسبوعاً بأسبوع وشهراً بشهر، وما بعدها لا يقرؤه مراقبٌ ولا مدقّق.
--
-- وظيفةٌ ليليّةٌ واحدة في pg_cron (٣:٤١ فجراً UTC — بعد وظيفة المجتمعات ٣:١٧ لا معها). `cron.schedule` بالاسم
-- يستبدل الوظيفةَ إن وُجدت، فإعادةُ التشغيل آمنة. لا يُلمس جدولٌ ولا منح.
--
-- ↩️ التراجع: select cron.unschedule('loopz-runtime-errors-retention');

select cron.schedule(
  'loopz-runtime-errors-retention',
  '41 3 * * *',
  $cron$ delete from public.runtime_errors where at < now() - interval '90 days'; $cron$
);

-- ============================================================
-- 165 — مدّةُ المؤسِّسين ثلاثةُ أشهرٍ لا مدى الحياة (D-833)
-- ============================================================
-- **حكمُ أحمد**: «الحسابات الموجودة كلها عطهم بلس مدة ٣ أشهر فقط — ٣
-- أشهر من تاريخ اليوم» — **ثمّ، بعد أن عُرض عليه أنّ الوعدَ منشورٌ في
-- ثلاث صفحاتٍ حيّةٍ إحداها «الشروط»**: «نفّذها وأصلح الوعد معها».
--
-- ⚖️ **ونقضٌ صريحٌ لـD-633 بيد صاحبه** — **وهي التي كتبت «مدى الحياة»
-- وقالت «لا خدمةَ تُنتزع من عضوٍ قائم».** **والنقضُ يُسجَّل ولا يُدسّ**،
-- **والنصوصُ الثلاثةُ تتغيّر في الدفعة نفسِها** — **وقاعدةٌ تقول شيئاً
-- وصفحةٌ تعد بغيره هي الكذبُ بعينه** (D-217).
--
-- 🔑 **ولا تُمسّ `founder`**: **الصفةُ باقيةٌ لأصحابها أبداً** — **وهي
-- ما لا يُنتزع** — **وشارتُها فُصلت عن انتهاء الاشتراك في الشيفرة**
-- (`AccountIdentity`)، **فمن سجّل مبكّراً يبقى مؤسِّساً بعد المدّة.**
--
-- ⚠️ **وحسابُ المنصّة خارجَ التحديث**: **ليس عضواً** — **والشرطُ
-- `created_at is not null` في `auth.users` هو نفسُه الذي ميّزه في ١٦٤.**
--
-- ⚠️ **وقيمةُ `plan` لا تتغيّر**: تبقى `plus` — **والعرضُ العامُّ يخفضها
-- إلى `free` من نفسِه عند انقضاء `plus_until`** (الهجرة ١٥٦)،
-- **و`isPlus()` تقرأ التاريخَ** — **فالانتهاءُ يقع مرّةً واحدةً في مكانٍ
-- واحد.**
-- ============================================================

update public.profiles p
   set plus_until = now() + interval '3 months'
 where p.plan <> 'free'
   and p.plus_until is null
   and exists (
     select 1 from auth.users u
      where u.id = p.id and u.created_at is not null
   );


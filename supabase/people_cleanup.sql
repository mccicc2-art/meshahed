--  ٨٦ — people_cleanup · **إسقاطُ دالّتين بلا قارئ** (D-270)
--  ⚠️ **تُشغَّل بعد أن تصل الشيفرة، لا قبلها** — انظر أدناه.
--
--  ================= لماذا هذه وحدها تُشغَّل أخيراً =================
--
--  **كلُّ هجرةٍ قبلها تُشغَّل قبل شيفرتها** (D-028): الشيفرةُ تنادي شيئاً
--  جديداً، **فالجديدُ يسبقها وإلا نادت العدم.**
--  **وهذه عكسُها تماماً**: تحذف شيئاً **تناديه الشيفرةُ الحيّة الآن**.
--  **فترتيبُ الحذف معكوسُ ترتيب الإضافة** — يُحذف القارئُ أوّلاً ثم
--  المقروء، **وإسقاطُها اليوم يُفرغ قسماً في الإنتاج قبل أن تصل النسخةُ
--  التي لا تناديه.**
--
--  ================= ولماذا تُحذفان أصلاً =================
--
--  **`people_watching`** — قسمُها «أضافوها إلى مكتباتهم» **حذفه أحمد
--  بالحرف**: «"Added to their libraries" ما نبغى». **وكانت تعمل بلا عطل**،
--  والحذفُ حكمُ صاحبِ المنتج لا حكمٌ على الشيفرة.
--
--  **`title_talk_stats`** — قارئُها `getTalkStats` سقط في D-266 حين صار
--  للنقاش مصدرُه (`title_talk_rooms`)، **وبقيت هي في القاعدة شهراً بلا
--  نداء.** **ودالّةٌ حيّةٌ بلا قارئ ليست حيادية**: تُقرأ في كل مراجعةٍ
--  أمناً، وتُصان عند كل تغييرِ عمود، **وتُغري بإحيائها لأنها «موجودة»**
--  (D-214: ما لا قارئَ له يُحذف، ولا يُترك «احتياطاً»).
--
--  ================= وما لا يُحذف هنا =================
--
--  ⚠️ **`people_to_follow` تبقى**: قسمُها في اللوحة حُذف، **لكن شاشةَ
--  التهيئة تناديها منذ D-126** (`suggestPeople` في `actions.ts`).
--  **يُفحص المستهلك قبل الحذف** — وهو الفحصُ الذي أهملتُه في D-267 فبنيتُ
--  بحثاً كان مبنيّاً في سطحٍ آخر.
--
--  ولا جدولَ ولا عمودَ ولا سياسةَ خامسة، وآمنةٌ للإعادة.
-- ============================================================

begin;

--  **بتوقيعها كاملاً لا باسمها** (D-037): `drop function` بلا معاملاتٍ
--  تفشل حين يكون للاسم أكثرُ من نسخة — **والفشلُ هنا خيرٌ من إسقاطِ
--  نسخةٍ لم تُقصد**، ولذلك يُكتب التوقيع.
drop function if exists public.people_watching(integer);
drop function if exists public.title_talk_stats();

commit;


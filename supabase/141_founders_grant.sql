-- 141: المؤسِّسون (D-633) — **هجرةُ بياناتٍ بإذنٍ صريحٍ من أحمد**:
-- «نعم امنح المؤسسين». وهي الهجرةُ الوحيدةُ في هذه الجولة التي تكتب في
-- صفوفٍ قائمة.
--
-- **الحجّة**: التنسيقُ والثيماتُ مشحونةٌ مجّانيّةٌ اليوم ويستعملها ثلثُ
-- الأعضاء (١٢ من ٣١ على ثيمٍ غير الافتراضيّ، و١٠ خصّصوا الهوم، و٤
-- البروفايل) — **وقاعدةُ أحمد: «لم أمنع خدمات مجانية على الأعضاء».**
-- فمن سجّل قبل الإعلان يأخذ البلس مدى الحياة: **لا خدمةَ تُنتزع من أحد،
-- والبوّابةُ تُبنى على الجمهور الذي لم يأتِ بعد.**
--
-- `plus_until` تبقى NULL عمداً = **بلا انتهاء** (وهو ما يقرؤه `isPlus`).
-- والحسابُ النظاميُّ (`is_system`) خارجٌ: ليس عضواً يُكافأ.
update public.profiles
set founder = true,
    plan = 'plus'
where not coalesce(is_system, false)
  and plan = 'free';

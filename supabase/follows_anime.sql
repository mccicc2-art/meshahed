-- ============================================================
--  ٦١ — علَمُ الأنمي على المتابعة نفسها (D-182)
--
--  **تبويبُ أنمي في المكتبة، ومن أين يعرف ما هو أنمي.**
--
--  الطريق المرفوض أوّلاً، لأن رفضَه هو القرار: **لا يُقرأ من
--  `imdb_pool.is_anime`.** بِركةُ تلك القائمة ~٤٠٠٠ مرشّح بعتبة خمسة
--  آلاف صوتٍ وتقييمٍ ٧٫٥ — أي أنها بِركةُ «أفضل الأعمال» لا سجلُّ ما
--  يتابعه الناس. فأنمي المستخدم المتوسّط ليس فيها، **فكان التبويب
--  سيُخفي نصفَ مكتبته ويدّعي الاكتمال** — وهو أسوأُ من ألّا يوجد.
--
--  فالعلَم يسكن الصفَّ الذي يخصّ صاحبه: `follows.is_anime`.
--
--  **ولماذا `null` مسموحة ولا افتراضَ `false`:** الفرق بين «ليس أنمي»
--  و«لم يُصنَّف بعد» هو كلُّ ما يجعل التعبئة الخلفيّة ممكنة ومتكرّرة بلا
--  ضرر. لو بدأ العمود `false` لصار كلُّ صفٍّ قديم يقول «ليس أنمي» بثقة،
--  ولا سبيل لتمييز ما لم يُسأل عنه. (نفسُ تمييز D-172 بين «لا تقييم»
--  و«لم نصل».)
--
--  ولا سياسةَ قراءةٍ جديدة: العمود يسكن جدولاً قائماً بسياساته —
--  **تبقى أربعاً.**
--  ترتيب التشغيل: بعد ٦٠.
-- ============================================================

alter table public.follows
  add column if not exists is_anime boolean;

-- القراءةُ الشائعة: «أنمي هذا المستخدم» و«ما لم يُصنَّف له بعد».
-- والفهرس جزئيٌّ عمداً — الصفوفُ التي تعنينا قليلةٌ من كثير
create index if not exists follows_user_anime_idx
  on public.follows (user_id, is_anime);

